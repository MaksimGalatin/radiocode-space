"use client";

import { useEffect } from "react";

/**
 * ── СКВОЗНОЙ ВХОД: КЛИЕНТСКАЯ ПОЛОВИНА ─────────────────────────────────
 *
 * Один аккаунт на четыре сайта. Слова Архитектора 09.09.2026: «у нас ДОЛЖЕН
 * быть единый вход и память у одного пользователя ВЕЗДЕ должна быть ЕДИНАЯ,
 * как и доход от рефералов и собираемые монеты… Один аккаунт на ВСЕ 4 сайта».
 *
 * ЧТО ДЕЛАЕТ. Если на ЭТОМ домене сессии нет, один раз за вкладку уводит
 * браузер к хранителю входа (центральный сайт) за билетом и возвращает
 * обратно уже со своей кукой. Человек видит только короткий переход.
 *
 * ПОЧЕМУ НЕ ФОНОВЫМ ЗАПРОСОМ. Куки третьих сторон в современных браузерах
 * заблокированы: тихо спросить чужой домен «а он у тебя вошёл?» больше
 * нельзя. Работает только настоящий переход.
 *
 * ЗАЩИТА ОТ ЗАЦИКЛИВАНИЯ — три слоя:
 *   1. отметка в `sessionStorage`: одна попытка на вкладку;
 *   2. ответ `aifa_sso=none` от центрального означает «там тоже не вошли» —
 *      после него не пробуем вовсе;
 *   3. на самом центральном сайте компонент не делает ничего: незачем
 *      спрашивать вход у самого себя.
 *
 * ЧЕГО КОМПОНЕНТ НЕ ДЕЛАЕТ. Не трогает страницы входа и регистрации — иначе
 * человек, вышедший нарочно, тут же уезжал бы обратно.
 */

const ХРАНИТЕЛЬ = "https://www.codeofdigitaleternity.com";
const ОТМЕТКА = "aifa_sso_tried";

/** Домены, на которых мост не нужен: хранитель входа — сам себе источник. */
function этоХранитель(host: string): boolean {
  return host === "codeofdigitaleternity.com" || host === "www.codeofdigitaleternity.com";
}

/** Страницы, с которых уводить нельзя. */
function страницаВхода(path: string): boolean {
  return /\/(login|signin|register|signup|auth|reset-password|logout)(\/|$)/i.test(path);
}

export default function СквознойВход() {
  useEffect(() => {
    try {
      const адрес = new URL(window.location.href);

      // Центральный сайт вернул «там тоже нет входа» — запоминаем и чистим
      // адрес, чтобы пометка не осталась в закладке и не ушла в аналитику.
      if (адрес.searchParams.get("aifa_sso") === "none") {
        try { sessionStorage.setItem(ОТМЕТКА, "1"); } catch { /* приватный режим */ }
        адрес.searchParams.delete("aifa_sso");
        window.history.replaceState({}, "", адрес.toString());
        return;
      }

      if (этоХранитель(адрес.hostname)) return;
      if (страницаВхода(адрес.pathname)) return;

      let пробовали = "0";
      try { пробовали = sessionStorage.getItem(ОТМЕТКА) || "0"; } catch { пробовали = "1"; }
      if (пробовали === "1") return;

      // Спрашиваем СВОЙ сервер: есть ли здесь сессия. Своя ручка, свои куки —
      // никаких ограничений на третьи стороны.
      fetch("/api/auth/me", { credentials: "include", cache: "no-store" })
        .then((r) => (r.ok ? r.json() : null))
        .then((d) => {
          const вошёл = !!(d && (d.email || (d.user && d.user.email)));
          if (вошёл) return;
          try { sessionStorage.setItem(ОТМЕТКА, "1"); } catch { /* приватный режим */ }
          const куда = new URL(`${ХРАНИТЕЛЬ}/api/auth/handoff`);
          куда.searchParams.set("return", window.location.href);
          window.location.replace(куда.toString());
        })
        .catch(() => { /* сеть подвела — просто оставляем как есть */ });
    } catch { /* ничего не ломаем ради удобства */ }
  }, []);

  return null;
}
