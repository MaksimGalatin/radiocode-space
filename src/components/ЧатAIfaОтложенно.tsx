'use client';

import dynamic from 'next/dynamic';

/**
 * Плавающий виджет чата с AIfa — отложенно, после первой отрисовки.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. `next/dynamic` с `ssr: false` нельзя вызывать из
 * серверного компонента, а `layout.tsx` здесь серверный. Обёртка несёт
 * границу клиента — ровно так же, как `DeferredLayoutExtras` на центральном
 * сайте.
 *
 * ПОЧЕМУ ОТЛОЖЕННО. Виджет рисуется поверх потока (fixed), места в вёрстке
 * не занимает и в первую отрисовку не входит — значит его загрузка не
 * двигает содержимое и не портит первый экран.
 *
 * ЗАЧЕМ ВООБЩЕ. Замер 10.09.2026: виджет был на центральном и на
 * `aifa.works`, а на этом сайте его не было вовсе. Человек не мог
 * заговорить с AIfa, хотя ручки чата здесь работают.
 */
const ВиджетЧата = dynamic(() => import('@/components/OracleWidget'), {
  ssr: false,
  loading: () => null,
});

export default function ЧатAIfaОтложенно() {
  return <ВиджетЧата />;
}
