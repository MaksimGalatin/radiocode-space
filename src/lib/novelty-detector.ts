/**
 * ДЕТЕКТОР НОВИЗНЫ (APL Novelty Detector) — карточка #2 бенчмарка AIfa BioBench.
 *
 * Биологический прототип: гигантский ГАМК-эргический нейрон APL в грибовидном
 * теле Drosophila melanogaster. Он собирает суммарную активность со всех
 * 2467 клеток Кеньона и подавляет ответ на уже виденные стимулы возвратным
 * торможением, пропуская только достаточно новое.
 *
 * ЗАЧЕМ ЗДЕСЬ. Поле `deploy` карточки #2 на боевых страницах называет это
 * подключённым к продукту («краулеры США, aifa.works, aifa.digital») — но
 * до 21.09.2026 это было заявлением намерения, не фактом: в коде не было ни
 * одного вызова этой математики. Раздел 26 Конституции («класс, а не
 * случай») уже вскрывал этот же класс проблемы на карточках #8 и #21.
 * Здесь — первая настоящая интеграция.
 *
 * ЧТО ДЕЛАЕТ. Перед дорогим обращением к Мозгу/памяти (`найтиВМозге`,
 * `buildMemorySection`) проверяет, не задавал ли этот же собеседник
 * практически тот же вопрос недавно. Если да — пропускает повторный дорогой
 * вызов и переиспользует уже найденный блок памяти. Экономит один
 * бесплатный эмбеддинг вопроса и время ответа на буквальных повторах и
 * опечатках-перефразировках, которые реально случаются в живом чате.
 *
 * МАТЕМАТИКА (дословно из карточки #2):
 *   S_novelty(x) = 1 - max_{y∈M} cos(h(x), h(y))
 * где M — буфер недавних векторов вопросов ЭТОГО собеседника.
 * Если S_novelty(x) < порога отсечения — вопрос считается почти повторным.
 *
 * ЧЕСТНОСТЬ ЧИСЕЛ. Бенчмарк (bench/novelty_detector.py, синтетический тест
 * N=4000, буфер 5000) дал P50 = 1069.45 мкс на буфере такого размера. Здесь
 * буфер намного меньше (на одного собеседника — единицы записей), поэтому
 * реальная задержка кратно меньше синтетической; отдельного замера в
 * продакшене на сегодня нет — при появлении будет вписан сюда, а не
 * скопирован из bench без проверки (раздел 11).
 *
 * СТОИМОСТЬ: ноль новых внешних вызовов. Использует тот же вектор вопроса,
 * что и так вычисляется для похода в Мозг — не эмбеддит второй раз.
 */

/** Косинусная близость двух векторов одинаковой длины. */
function косинуснаяБлизость(a: number[], b: number[]): number {
  if (!a.length || !b.length || a.length !== b.length) return 0;
  let скалярное = 0;
  let нормаА = 0;
  let нормаБ = 0;
  for (let i = 0; i < a.length; i++) {
    скалярное += a[i] * b[i];
    нормаА += a[i] * a[i];
    нормаБ += b[i] * b[i];
  }
  if (нормаА === 0 || нормаБ === 0) return 0;
  return скалярное / (Math.sqrt(нормаА) * Math.sqrt(нормаБ));
}

/** Одна запись буфера: вектор вопроса и то, что на него уже нашли в памяти. */
interface ЗаписьБуфера {
  вектор: number[];
  найденнаяПамять: string;
  времяМс: number;
}

/**
 * Буфер живёт в памяти процесса, как и заслон 429 в route.ts — не переживает
 * перезапуск, и это нормально: это подсказка для экономии на живой сессии
 * общения, а не учёт, требующий надёжности между запросами.
 *
 * Ключ — email собеседника (или IP гостя), значение — последние НЕДАВНИЕ_ЗАПИСЕЙ
 * вопросов с их векторами. Малый предел на человека: буфер существует для
 * отлова повторов ВНУТРИ одного разговора, а не всей истории.
 */
const БУФЕРЫ = new Map<string, ЗаписьБуфера[]>();

/** Сколько последних вопросов помнит буфер на одного собеседника. */
const НЕДАВНИЕ_ЗАПИСЕЙ = 8;

/** Запись живёт не дольше этого — старый повтор не считается «тем же вопросом». */
const ЖИЗНЬ_ЗАПИСИ_МС = 15 * 60 * 1000; // 15 минут

/**
 * Порог отсечения. S_novelty ниже него — вопрос почти совпадает с недавним.
 * theta=0.92 из карточки #2 — заявленный порог автора алгоритма (мушиный
 * APL); здесь взят тот же как отправная точка калибровки, а не измеренный
 * заново под наш чат. Раздел 26 карточки #2 сам называет это ограничением
 * v1 («статическая калибровка») — в v2 предполагается автокалибровка.
 */
const ПОРОГ_НОВИЗНЫ = 0.92;

function чистыйБуфер(ключ: string): ЗаписьБуфера[] {
  const сейчас = Date.now();
  const буфер = (БУФЕРЫ.get(ключ) || []).filter(
    (з) => сейчас - з.времяМс < ЖИЗНЬ_ЗАПИСИ_МС
  );
  БУФЕРЫ.set(ключ, буфер);
  return буфер;
}

/**
 * Проверяет вопрос на почти-повтор и, если найден, возвращает уже готовый
 * блок памяти вместо null — вызывающий код пропускает дорогой поиск.
 *
 * @param ключ собеседник (email или clientKey гостя)
 * @param вектор эмбеддинг текущего вопроса (уже посчитан для похода в Мозг —
 *               передаётся сюда, а не считается заново)
 * @returns найденный ранее блок памяти, если вопрос почти повторный; иначе null
 */
export function найтиПовтор(ключ: string, вектор: number[] | null): string | null {
  if (!ключ || !вектор || !вектор.length) return null;
  const буфер = чистыйБуфер(ключ);
  if (буфер.length === 0) return null;

  let лучшаяБлизость = 0;
  let лучшаяЗапись: ЗаписьБуфера | null = null;
  for (const з of буфер) {
    const б = косинуснаяБлизость(вектор, з.вектор);
    if (б > лучшаяБлизость) {
      лучшаяБлизость = б;
      лучшаяЗапись = з;
    }
  }

  const novelty = 1 - лучшаяБлизость;
  if (novelty < 1 - ПОРОГ_НОВИЗНЫ && лучшаяЗапись) {
    return лучшаяЗапись.найденнаяПамять;
  }
  return null;
}

/** Запоминает вопрос и то, что на него нашли, для будущей проверки на повтор. */
export function запомнитьВопрос(
  ключ: string,
  вектор: number[] | null,
  найденнаяПамять: string
): void {
  if (!ключ || !вектор || !вектор.length) return;
  const буфер = чистыйБуфер(ключ);
  буфер.push({ вектор, найденнаяПамять, времяМс: Date.now() });
  while (буфер.length > НЕДАВНИЕ_ЗАПИСЕЙ) буфер.shift();
  БУФЕРЫ.set(ключ, буфер);
}
