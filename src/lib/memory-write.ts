/**
 * ДОСЛОВНАЯ ЗАПИСЬ ПЕРЕПИСКИ — ОДНА ФУНКЦИЯ НА ВСЕХ, КТО ПИШЕТ.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. У памяти два слоя, и они писались по-разному:
 *
 *   • СМЫСЛОВОЙ (эмбеддинги в DATABASE_URL_VECTOR) пишется НА СЕРВЕРЕ, внутри
 *     /api/aifa-chat, и потому цел — 322 806 записей на день замера.
 *   • ДОСЛОВНЫЙ ЗАШИФРОВАННЫЙ (chat_memory и chat_memory_chunks в
 *     SUBMISSIONS_DB_URL) писался ИЗ БРАУЗЕРА отдельным запросом на
 *     /api/memory/append после каждого ответа.
 *
 * Замер в боевой базе: в дословном слое значение chat_type бывает ТОЛЬКО
 * 'terminal' и 'oracle', а 'main' нет НИ У КОГО. То есть разговоры главного
 * чата дословно не сохранялись вообще. Причина в самой схеме: отдельный запрос
 * из браузера не уходит, если человек закрыл вкладку сразу после ответа, если
 * моргнула сеть, если страница публичная и сессии нет. Смысловой слой при этом
 * цел именно потому, что пишется на сервере — там же, где родился ответ.
 *
 * ПОЭТОМУ логика записи вынесена сюда целиком и вызывается ДВАЖДЫ:
 *   1) из /api/aifa-chat — на сервере, сразу после ответа модели (надёжный путь);
 *   2) из /api/memory/append — по старому запросу браузера (совместимость:
 *      AIfaFocus и сайты-спутники продолжают звать ручку как звали).
 *
 * Дублирования не будет: перед записью считается отпечаток пары «вопрос-ответ»,
 * и если такая пара уже лежит последней в памяти этого человека — мы молча
 * выходим. Подробности у `отпечатокПоследнейПары` и у guarded-UPDATE ниже.
 */
import crypto from 'crypto';
import { after } from 'next/server';
import { getOrCreateUserKey, encryptWithUserKey, decryptWithUserKey } from './user-key';
import { SEAL_THRESHOLD, ensureChunkTable } from './memory-archive';
import { маскаПочты } from './log-privacy';

/** Потолки одной реплики — ровно те же, что были в ручке /api/memory/append. */
const МАКС_ВОПРОС = 8000;
const МАКС_ОТВЕТ = 12000;

/** Сколько раз перечитываем и пробуем снова, если строку изменили под нами. */
const ПОПЫТОК = 3;

export type ПричинаОтказа =
  | 'no_email'        // человек не вошёл — писать некуда и незачем
  | 'empty'           // пустая пара
  | 'no_db'           // не задан SUBMISSIONS_DB_URL
  | 'prev_unreadable' // прежняя запись не расшифровалась — историю не трогаем
  | 'conflict'        // строку меняли под нами все попытки подряд
  | 'key_error'
  | 'db_error';

export type ИсходЗаписи =
  | { ok: true; повтор: boolean }
  | { ok: false; причина: ПричинаОтказа };

/**
 * Отпечаток пары «вопрос — ответ»: ТОЛЬКО содержание, без времени.
 *
 * Время намеренно не входит: сервер и браузер пишут один и тот же ход в разные
 * миллисекунды, и по метке времени пара выглядела бы разной. Сравнивать надо то,
 * что сказано, а не когда записано.
 */
export function отпечатокПары(вопрос: string, ответ: string): string {
  const в = вопрос.trim();
  const о = ответ.trim();
  // Длина вопроса впереди — чтобы пары («а», «бв») и («аб», «в») не свелись к
  // одному отпечатку: без неё склейка двух текстов неоднозначна.
  return crypto.createHash('sha256').update(`${в.length}|${в}${о}`, 'utf8').digest('hex');
}

/**
 * Заголовок реплики в дословном архиве: «### [ГГГГ-ММ-ДД ЧЧ:ММ:СС] Кто».
 * Формат даты задан жёстко — иначе строка «### [Заметка] Важное» внутри самого
 * сообщения была бы принята за начало новой реплики.
 */
const ЗАГОЛОВОК_РЕПЛИКИ = /###\s*\[\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\]\s*([^\n\r]+)\r?\n/g;

/** Тело реплики без окружающих пробелов и без хвостового разделителя «---». */
function телоРеплики(кусок: string): string {
  let т = кусок.trim();
  if (т.endsWith('---')) т = т.slice(0, -3).trim();
  return т;
}

function этоAIfa(имя: string): boolean {
  return имя === 'AIfa' || имя === 'assistant';
}

/**
 * Отпечаток ПОСЛЕДНЕЙ пары в готовом блобе памяти — или null, если хвост не
 * похож на пару «человек, потом AIfa».
 *
 * Это и есть защита от удвоения: один и тот же ход теперь пишут двое (сервер
 * сразу после ответа и браузер следом), и второй обязан увидеть, что первый уже
 * записал. Сравнение идёт по содержанию, поэтому разные метки времени не мешают.
 *
 * Ошибаемся в безопасную сторону: если хвост не разобрался, возвращаем null и
 * запись состоится. Лишняя копия реплики — беда поправимая, потерянная реплика —
 * нет.
 */
export function отпечатокПоследнейПары(память: string): string | null {
  if (!память) return null;
  const рег = new RegExp(ЗАГОЛОВОК_РЕПЛИКИ.source, 'g');
  let м: RegExpExecArray | null;
  let предпоследний: { конец: number; имя: string } | null = null;
  let последний: { начало: number; конец: number; имя: string } | null = null;
  while ((м = рег.exec(память)) !== null) {
    предпоследний = последний ? { конец: последний.конец, имя: последний.имя } : null;
    последний = { начало: м.index, конец: м.index + м[0].length, имя: м[1].trim() };
  }
  if (!последний || !предпоследний) return null;
  if (!этоAIfa(последний.имя) || этоAIfa(предпоследний.имя)) return null;
  const вопрос = телоРеплики(память.slice(предпоследний.конец, последний.начало));
  const ответ = телоРеплики(память.slice(последний.конец));
  return отпечатокПары(вопрос, ответ);
}

/** Класс причины по тексту исключения — ключ наружу, разумеется, не уходит. */
function классОшибки(e: unknown): ПричинаОтказа {
  const msg = String((e as { message?: string })?.message || e);
  return /MEMORY_MASTER_KEY|KMS|kms|Unsupported state|bad decrypt|unable to authenticate/.test(msg)
    ? 'key_error'
    : 'db_error';
}

/**
 * Дописывает один ход разговора в дословную зашифрованную память человека.
 *
 * @param email    почта владельца памяти; пусто — не пишем (человек не вошёл)
 * @param chatType канал ('main' | 'terminal' | 'oracle' и т.п.)
 * @param at       время реплики; нужно при восстановлении утраченной переписки,
 *                 чтобы старый разговор не лёг сегодняшним числом
 * @param опции    индексироватьСмысл: после НОВОЙ записи положить пару и в поиск по смыслу.
 *                 По умолчанию выключено: чат центрального индексирует ход сам (indexTurn), и второй
 *                 вызов означал бы плату за те же эмбеддинги дважды. Включают пути, у которых своей
 *                 индексации нет (запасной чат и оракул на works). Одинаково на 4 сайтах (30.09.2026).
 */
export async function appendVerbatim(
  email: string,
  chatType: string,
  userMessage: string,
  assistantMessage: string,
  at?: string | Date,
  опции?: { индексироватьСмысл?: boolean }
): Promise<ИсходЗаписи> {
  const em = String(email || '').trim().toLowerCase();
  if (!em) return { ok: false, причина: 'no_email' };

  // Обрезаем и подравниваем ОДИНАКОВО для обоих путей записи. Иначе сервер и
  // браузер дали бы чуть разный текст одного и того же хода, отпечатки не
  // совпали бы, и защита от удвоения не сработала бы именно там, где нужна.
  const вопрос = String(userMessage ?? '').trim().slice(0, МАКС_ВОПРОС);
  const ответ = String(assistantMessage ?? '').trim().slice(0, МАКС_ОТВЕТ);
  if (!вопрос && !ответ) return { ok: false, причина: 'empty' };

  const вид = String(chatType || '').trim().toLowerCase().slice(0, 24) || 'main';

  const url = process.env.SUBMISSIONS_DB_URL;
  if (!url) return { ok: false, причина: 'no_db' };

  // Время реплики. Обычно текущее, но при восстановлении утраченной переписки
  // можно передать исходное. Проверяем: значение должно разбираться как дата и
  // не быть из будущего (допуск пять минут на расхождение часов).
  let когда = new Date();
  if (at) {
    const разобрано = at instanceof Date ? at : new Date(String(at).trim());
    if (!Number.isNaN(разобрано.getTime()) && разобрано.getTime() <= Date.now() + 5 * 60_000) {
      когда = разобрано;
    }
  }
  const ts = когда.toISOString().replace('T', ' ').slice(0, 19);
  const запись = `### [${ts}] User\n${вопрос}\n\n---\n\n### [${ts}] AIfa\n${ответ}\n\n---\n\n`;
  const мойОтпечаток = отпечатокПары(вопрос, ответ);

  try {
    const { Pool } = await import('@neondatabase/serverless');
    const pool = new Pool({ connectionString: url });
    try {
      // Ключ человека берём ОДИН раз на весь вызов. Раньше каждая операция
      // (расшифровать прежнее, убедиться, что ключ есть, зашифровать новое)
      // тянула его заново, а каждое такое обращение — это запрос в базу и
      // стотысячная прокрутка pbkdf2. Один ключ на вызов оставляет запас на
      // проверку соседних каналов ниже, не удорожая запись.
      const ключ = await getOrCreateUserKey(em);

      for (let попытка = 1; попытка <= ПОПЫТОК; попытка++) {
        // Читаем ВСЕ каналы человека сразу, одним запросом.
        //
        // ПОЧЕМУ ВСЕ, а не только свой. Терминал зовёт /api/aifa-chat с
        // chatType='main', а браузерную дозапись шлёт с chatType='terminal' —
        // это его давняя особенность. Проверяй мы только свой канал, один и тот
        // же ход лёг бы дважды: разом в 'main' (с сервера) и в 'terminal' (из
        // браузера). Проверка по всем каналам делает защиту независимой и от
        // такой рассинхронизации, и от того, кто из двоих успел первым.
        const все = await pool.query(
          `SELECT chat_type, ciphertext FROM chat_memory WHERE email=$1`, [em]);

        let свояСтрокаЕсть = false;
        let прежнийШифр: string | null = null;
        let прежнее = '';
        let ужеЕсть = false;

        for (const строка of все.rows as Array<{ chat_type: string; ciphertext: string | null }>) {
          const свой = строка.chat_type === вид;
          // «Строка есть» и «в строке что-то лежит» — разные вещи. Пустую строку
          // надо ОБНОВИТЬ, а не вставлять заново: вставка наткнулась бы на
          // уникальный ключ, ничего не сделала, и ход потерялся бы молча.
          if (свой) { свояСтрокаЕсть = true; прежнийШифр = строка.ciphertext || null; }
          if (!строка.ciphertext) continue;
          let текст: string;
          try {
            // ОТКРЫТЫЙ ТЕКСТ ИЛИ ШИФР — понимаем оба (16.08.2026). По разделу 10
            // Конституции база переводится на открытый текст, и во время
            // перевода в таблице лежат оба вида одновременно. Дословная
            // переписка всегда начинается с отметки реплики `### [`, а
            // шифротекст — base64, так начинаться не может.
            текст = строка.ciphertext.trimStart().startsWith('###')
              ? строка.ciphertext
              : decryptWithUserKey(ключ, строка.ciphertext);
          } catch (e) {
            // ЕСЛИ НЕ ЧИТАЕТСЯ СВОЙ КАНАЛ — НИЧЕГО НЕ ПИШЕМ.
            //
            // Здесь была тихая потеря всей переписки: prev просто обнулялся, а
            // строка ниже перезаписывается целиком — то есть одна неудачная
            // расшифровка стирала всю историю человека и заменяла её одной
            // последней репликой, молча, с ответом «ok». Лучше потерять одну
            // реплику, чем всю память.
            //
            // Чужой канал в такой ситуации просто пропускаем: он нужен нам лишь
            // для проверки на повтор, и его нечитаемость нашей записи не мешает.
            if (свой) {
              console.error(
                '[память] прежняя запись не расшифровалась — запись прервана, история сохранена',
                маскаПочты(em), вид, e);
              return { ok: false, причина: 'prev_unreadable' };
            }
            continue;
          }
          if (свой) прежнее = текст;
          if (отпечатокПоследнейПары(текст) === мойОтпечаток) ужеЕсть = true;
        }

        // Эта пара уже записана (нами же с другой стороны) — выходим молча.
        if (ужеЕсть) return { ok: true, повтор: true };

        // Seal-instead-of-trim: историю не выбрасываем никогда. Когда живой блоб
        // перерастает порог, прежняя переписка замораживается в неизменяемый
        // кусок (< ~91 КБ шифротекста → бесплатный тир Arweave), а живой блоб
        // начинается заново с новой записи.
        let живое = прежнее + запись;
        const надоЗапечатать = Buffer.byteLength(живое, 'utf8') > SEAL_THRESHOLD && !!прежнее;
        if (надоЗапечатать) {
          await ensureChunkTable(pool);
          const idxRes = await pool.query(
            `SELECT COALESCE(MAX(chunk_index),0)+1 AS n FROM chat_memory_chunks WHERE email=$1 AND chat_type=$2`,
            [em, вид]);
          const следующий = Number(idxRes.rows[0].n);
          await pool.query(
            /*
            * ЗАЩИТА ОТ ПОВТОРА ПО СОДЕРЖИМОМУ, а не только по номеру.
            *
            * НАЙДЕНО ЗАМЕРОМ 26.08.2026: из 17 архивных кусков 15 разных —
            * у двух человек куски 1 и 2 оказались ПОБАЙТОВО одинаковыми,
            * и каждый уехал в блокчейн отдельным адресом. Оттуда не
            * изымается ничего: повтор там теперь навсегда, и при сборке
            * архива этот отрезок разговора читается дважды.
            *
            * Как выходит: две записи, идущие одновременно, видят один и тот
            * же `прежнее`, обе решают запечатать, и MAX(chunk_index)+1 даёт
            * им РАЗНЫЕ номера — 1 и 2. Прежняя защита ловила совпадение
            * номера и такой случай пропускала.
            *
            * Сверяем по md5, а не по всему тексту: куски бывают под сто
            * килобайт, и сравнивать их целиком на каждой записи дорого.
            */
            `INSERT INTO chat_memory_chunks(email,chat_type,chunk_index,ciphertext)
            SELECT $1,$2,$3,$4
            WHERE NOT EXISTS (
            SELECT 1 FROM chat_memory_chunks
            WHERE email=$1 AND chat_type=$2 AND md5(ciphertext)=md5($4::text))
            ON CONFLICT(email,chat_type,chunk_index) DO NOTHING`,
            // В базу кладём ОТКРЫТЫЙ ТЕКСТ (раздел 10 Конституции). Шифруется
            // только то, что уходит в Arweave: цепь публична и необратима, а
            // база защищена шифрованием диска, входом и правами. Прикладное
            // шифрование здесь уже стоило нам 227 нечитаемых реплик из 665.
            [em, вид, следующий, прежнее]);
          живое = запись;
        }

        // Живой блок — тоже открытым текстом (раздел 10 Конституции).
        // Переменная сохраняет прежнее имя: её отпечаток сравнивается сторожем
        // записи ниже, и переименование потребовало бы трогать эту логику.
        const шифр = живое;

        // ЗАПИСЬ СО СТОРОЖЕМ: меняем строку только если она осталась ровно той,
        // которую мы прочитали. Ход теперь пишут двое почти одновременно, и
        // безусловный UPDATE молча затирал бы работу второго (а до этой правки
        // так же тихо терялись и две быстрые реплики подряд). Не сошлось —
        // перечитываем: на втором заходе чужая запись уже видна, отпечаток
        // совпадёт, и мы просто выйдем как «повтор».
        const записано = !свояСтрокаЕсть
          ? await pool.query(
              `INSERT INTO chat_memory(email, chat_type, ciphertext) VALUES($1,$2,$3)
               ON CONFLICT(email, chat_type) DO NOTHING RETURNING 1 AS ok`,
              [em, вид, шифр])
          // IS NOT DISTINCT FROM, а не «=»: сравнение с NULL через «=» даёт NULL,
          // то есть «не подошло», и пустая строка не обновилась бы никогда.
          : await pool.query(
              `UPDATE chat_memory SET ciphertext=$3, updated_at=now()
               WHERE email=$1 AND chat_type=$2 AND ciphertext IS NOT DISTINCT FROM $4 RETURNING 1 AS ok`,
              [em, вид, шифр, прежнийШифр]);
        if (записано.rows.length) {
          // Хранение и припоминание — разные вещи: дословный слой лёг, но AIfa ВСПОМИНАЕТ по смыслу,
          // из отдельного хранилища векторов. Только по просьбе вызывающего и только для новой пары.
          if (опции?.индексироватьСмысл) {
            after(async () => {
              try {
                const { indexMessages, getSiteId } = await import('./memory-index');
                await indexMessages(em, вид, [
                  { role: 'user', content: вопрос, speaker: 'User' },
                  { role: 'assistant', content: ответ, speaker: 'AIfa' },
                ], getSiteId());
              } catch (idxErr) {
                console.warn('[память] запись в поиск по смыслу не удалась:', idxErr);
              }
            });
          }
          return { ok: true, повтор: false };
        }

        // Запечатанный кусок повторять НЕЛЬЗЯ: на новой попытке прежнее уже
        // включало бы чужую реплику и легло бы в архив вторым куском, задвоив
        // содержимое. Такое совпадение (переход через порог ровно в момент
        // чужой записи) редчайшее, и честнее пропустить одну реплику, чем
        // испортить архив.
        if (надоЗапечатать) {
          console.warn('[память] строку изменили при запечатывании куска — ход не дописан', маскаПочты(em), вид);
          return { ok: false, причина: 'conflict' };
        }
        console.warn(`[память] строку изменили под нами, попытка ${попытка} из ${ПОПЫТОК}`, маскаПочты(em), вид);
      }
      return { ok: false, причина: 'conflict' };
    } finally {
      try { await pool.end(); } catch { /* закрывать нечего — не беда */ }
    }
  } catch (e) {
    // Называем причину. «db_error» на всё подряд однажды стоил целого разбора:
    // база была исправна, а не работал ключ шифрования — и по ответу этого было
    // не видно.
    console.error('[память] дословная запись не удалась:', маскаПочты(em), вид, e);
    return { ok: false, причина: классОшибки(e) };
  }
}
