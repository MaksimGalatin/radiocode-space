/**
 * КЛЮЧ НА КАЖДЫЙ ДИАЛОГ — право на забвение в вечном хранилище.
 *
 * Требование Архитектора 25.08.2026, дословно: «у каждого пользователя его
 * личный шифроключ и его таблица — мы работаем как ПротонМэйл и другие:
 * ключ один, но каждый диалог шифруется отдельно при выгрузке в блокчейн,
 * чтобы можно было удалить ОДИН диалог стерев его ключ, а не всю память».
 * И там же: «мы это должны были уже давно доделать».
 *
 * ## Задача, которую это решает
 *
 * Из Arweave нельзя удалить запись. Никогда, никому, ни за какие деньги.
 * Человек при этом имеет право потребовать удаления своих данных — и это
 * право не отменяется тем, что мы выбрали вечное хранилище.
 *
 * Единственный существующий способ дать право на забвение там, где
 * удаление невозможно: сделать запись НЕЧИТАЕМОЙ. Запись остаётся в
 * цепочке навсегда, но превращается в шум, который никто не расшифрует —
 * включая нас.
 *
 * ## Почему производный ключ, а не отдельный хранимый
 *
 * Напрашивается таблица «ключ на диалог». Она плоха тем, что множит
 * секреты: каждый ключ надо обернуть мастер-ключом, хранить, ротировать,
 * бэкапить — и каждый становится новой точкой утечки.
 *
 * Здесь ключ диалога НЕ ХРАНИТСЯ. Он ВЫВОДИТСЯ из личного ключа человека и
 * случайной соли этого диалога:
 *
 *     ключ_диалога = HKDF-SHA256(ключ_пользователя, соль_диалога, метка)
 *
 * Хранится только соль — 16 случайных байт, сама по себе бесполезная.
 * Удаление диалога = удаление одной строки с солью. После этого вывести
 * ключ невозможно даже нам, даже имея мастер-ключ и личный ключ человека.
 *
 * Это то же, что делает ProtonMail и любая система «crypto-shredding»:
 * стирают не данные, а возможность их прочесть.
 *
 * ## Чего этот модуль НЕ делает
 *
 * Он НЕ мигрирует существующую память. Переход на пер-диалоговые ключи —
 * это перешифровка всего, что уже записано, и по разделу 10 Конституции
 * такое делается только так: расшифровать прежним ключом → зашифровать
 * новым → ПРОВЕРИТЬ ОБРАТНУЮ РАСШИФРОВКУ ДО ЗАПИСИ → сохранить копию.
 * Один неверный шаг превращает память в мусор, и обнаруживается это не
 * падением, а тем, что AIfa «забыла» человека.
 *
 * Поэтому здесь только механизм и его проверка. Решение о миграции и её
 * запуск — за Архитектором (разделы 18 и 35).
 */

import crypto from 'crypto';

/** Метка схемы. Меняется, только если меняется сам способ вывода ключа. */
export const СХЕМА_КЛЮЧА_ДИАЛОГА = 'aifa-dialog-key-v1';

/** Длина соли диалога в байтах. 16 — общепринятый минимум для HKDF. */
export const ДЛИНА_СОЛИ = 16;

/**
 * Новая соль для диалога. Хранится в базе рядом с диалогом.
 *
 * Сама по себе она не секрет: зная соль, но не зная личного ключа
 * человека, вывести ключ диалога нельзя. Но и наоборот: зная личный ключ,
 * но потеряв соль, — тоже нельзя. Именно на этом держится забвение.
 */
export function новаяСоль(): Buffer {
  return crypto.randomBytes(ДЛИНА_СОЛИ);
}

/**
 * Вывести ключ конкретного диалога.
 *
 * @param ключПользователя — 32 байта, из `user-key.ts`
 * @param соль — соль этого диалога из базы
 * @param идДиалога — попадает в `info` HKDF: два диалога с одинаковой
 *        солью (что почти невозможно) всё равно получат разные ключи
 */
export function ключДиалога(
  ключПользователя: Buffer,
  соль: Buffer,
  идДиалога: string,
): Buffer {
  if (ключПользователя.length !== 32) {
    throw new Error('ключ пользователя должен быть 32 байта');
  }
  if (!соль || соль.length < ДЛИНА_СОЛИ) {
    throw new Error(`соль диалога должна быть не меньше ${ДЛИНА_СОЛИ} байт`);
  }
  const инфо = Buffer.from(`${СХЕМА_КЛЮЧА_ДИАЛОГА}:${идДиалога}`, 'utf8');
  // hkdfSync возвращает ArrayBuffer — оборачиваем в Buffer.
  return Buffer.from(crypto.hkdfSync('sha256', ключПользователя, соль, инфо, 32));
}

/**
 * Зашифровать текст диалога.
 *
 * Формат: iv(12) + tag(16) + шифротекст, base64.
 * Соли внутри нет намеренно — она хранится в базе отдельно, и именно её
 * удаление делает запись нечитаемой. Положи мы соль в сам шифротекст,
 * забвение перестало бы работать: запись несла бы в себе всё нужное для
 * расшифровки.
 */
export function зашифроватьДиалог(ключ: Buffer, текст: string): string {
  const iv = crypto.randomBytes(12);
  const ш = crypto.createCipheriv('aes-256-gcm', ключ, iv);
  const шифр = Buffer.concat([ш.update(Buffer.from(текст, 'utf8')), ш.final()]);
  return Buffer.concat([iv, ш.getAuthTag(), шифр]).toString('base64');
}

/** Расшифровать. Бросает исключение, если ключ не тот, — так и надо. */
export function расшифроватьДиалог(ключ: Buffer, шифротекст: string): string {
  const сырое = Buffer.from(шифротекст, 'base64');
  if (сырое.length < 28) throw new Error('шифротекст короче заголовка');
  const iv = сырое.subarray(0, 12);
  const тег = сырое.subarray(12, 28);
  const тело = сырое.subarray(28);
  const д = crypto.createDecipheriv('aes-256-gcm', ключ, iv);
  д.setAuthTag(тег);
  return Buffer.concat([д.update(тело), д.final()]).toString('utf8');
}

/**
 * ПРОВЕРКА ЗАБВЕНИЯ — то, ради чего всё затевалось.
 *
 * Возвращает true, если без соли расшифровать НЕВОЗМОЖНО. Вызывается в
 * самопроверке: механизм, у которого забвение не доказано, бесполезен.
 *
 * Проверяется буквально: берём другую соль (как будто настоящая стёрта) и
 * убеждаемся, что расшифровка падает. Если бы она прошла — значит соль ни
 * на что не влияет, и удалять её бессмысленно.
 */
export function забвениеРаботает(
  ключПользователя: Buffer,
  идДиалога: string,
  образец: string,
): boolean {
  const соль = новаяСоль();
  const ключ = ключДиалога(ключПользователя, соль, идДиалога);
  const шифр = зашифроватьДиалог(ключ, образец);

  // 1. С правильной солью читается.
  if (расшифроватьДиалог(ключ, шифр) !== образец) return false;

  // 2. С другой солью — не читается. Это и есть забвение.
  const чужаяСоль = новаяСоль();
  const чужойКлюч = ключДиалога(ключПользователя, чужаяСоль, идДиалога);
  try {
    расшифроватьДиалог(чужойКлюч, шифр);
    return false; // прочиталось — забвение НЕ работает
  } catch {
    // ожидаемо: тег GCM не сошёлся
  }

  // 3. Тот же личный ключ, тот же диалог, но соль потеряна — не читается.
  //    Проверяется отдельно, потому что именно этот случай и наступает
  //    после удаления строки с солью.
  try {
    расшифроватьДиалог(ключДиалога(ключПользователя, новаяСоль(), идДиалога), шифр);
    return false;
  } catch {
    return true;
  }
}
