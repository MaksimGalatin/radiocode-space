/**
 * Не исчерпан ли суточный потолок вызовов.
 *
 * Считается по нашей таблице учёта, а не по счёту x.ai: счёт отстаёт и не
 * показывает часы. Тот же приём, что у Bedrock.
 *
 * Ошибка проверки НЕ закрывает путь: сторож не имеет права уронить то, что
 * сторожит. Но факт сбоя печатается — молчащий сторож хуже отсутствующего.
 */
async function потолокНеИсчерпан(): Promise<boolean> {
  // Два имени сознательно: кириллица в ИМЕНИ переменной окружения — риск,
  // который уже стоил нам сборки (имя файла `активный-язык.tsx` уронило
  // сборку на Linux, хотя на Windows собиралось). Латинское имя принимается
  // любой панелью и любым окружением, русское оставлено для читаемости.
  const предел = Number(
    process.env.GROK_DAILY_CALL_LIMIT
    || process.env.GROK_ЛИМИТ_ВЫЗОВОВ_В_СУТКИ
    || '30');
  if (!Number.isFinite(предел) || предел <= 0) return true;
  try {
    const { Pool } = await import('@neondatabase/serverless');
    // 🔴 БАЗА НЕ ТА. Найдено живым журналом боевого 13.09.2026:
    //
    //     [Grok] потолок проверить не удалось: relation
    //     "api_spend_hourly" does not exist
    //
    // Таблицу учёта ведёт `lib/cost-guard.ts`, и она подключается к
    // SUBMISSIONS_DB_URL — а потолок искал её в DATABASE_URL. Это РАЗНЫЕ
    // базы, поэтому проверка падала всегда, а падение здесь означает
    // «считаю предел не достигнутым». То есть суточного потолка у платного
    // пути НЕ БЫЛО НИ ОДНОГО ДНЯ — ни у Bedrock с 11.09, ни у Grok.
    // Сторож, который не может прочитать свою таблицу, не сторож.
    const строка = process.env.SUBMISSIONS_DB_URL || process.env.DATABASE_URL;
    if (!строка) return true;
    const pool = new Pool({ connectionString: строка });
    try {
      const r = await pool.query(
        `SELECT COALESCE(SUM(calls), 0)::int AS c FROM api_spend_hourly
          WHERE service = $1 AND hour_utc >= now() - interval '24 hours'`,
        [СЛУЖБА]
      );
      const было = Number(r.rows?.[0]?.c || 0);
      if (было >= предел) {
        console.warn(`[Grok] суточный потолок исчерпан: ${было} из ${предел} — не зову`);
        await письмоОдинРазВСутки(
          'Grok: суточный потолок исчерпан',
          `Платный резерв Grok сделал ${было} вызовов за сутки при пределе ${предел} `
          + `и больше не зовётся до смены суток.\n\n`
          + `Пока он закрыт, разговор идёт на встроенных ответах из базы знаний.\n`
          + `Поднять предел: переменная GROK_ЛИМИТ_ВЫЗОВОВ_В_СУТКИ.\n`
          + `Авто-пополнение в консоли x.ai выключено — само ничего не спишется.`
        );
        return false;
      }
      console.warn(`[Grok] потолок: ${было} из ${предел} за сутки`);
      if (было === 0) {
        await письмоОдинРазВСутки(
          'Grok включился — платный резерв в работе',
          `Бесплатные каналы замолчали, и разговор пошёл через платный Grok.\n\n`
          + `Ставки (консоль x.ai, замер 12.09.2026): вход $2.00 / 1M токенов, `
          + `выход $6.00 / 1M. Один ответ ≈ $0.016.\n`
          + `Предел на сутки: ${предел} вызовов ≈ $${(предел * 0.016).toFixed(2)}.\n`
          + `Авто-пополнение выключено: когда кредиты кончатся, Grok просто замолчит, `
          + `с карты не спишется ничего.`
        );
      }
      return true;
    } finally {
      try { await pool.end(); } catch { /* ignore */ }
    }
  } catch (e) {
    console.warn('[Grok] потолок проверить не удалось, считаю не достигнутым:',
      String(e).slice(0, 120));
    return true;
  }
}

/**
 * Один ответ от Grok или null.
 *
 * null значит «иди дальше» — здесь дальше только встроенный ответ из базы
 * знаний. Исключение бросать нельзя: оно оборвало бы разговор человека.
 */
export async function grokChatCompletion(
  messages: Array<{ role: string; content: string }>,
  maxTokens: number = 4096,
  temperature: number = 0.8
): Promise<string | null> {
  // 🔴 КАЖДЫЙ ОТКАЗ ВИДЕН. Оплачено вечером 12.09.2026: Bedrock молчал из-за
  // проглоченного ThrottlingException, и найти это можно было только прямым
  // вызовом мимо нашего кода. Здесь такого не повторится.
  const к = ключ();
  if (!к) {
    console.warn('[Grok] пропущен: ключа нет в окружении (XAI_API_KEY / GROK_API_KEY)');
    return null;
  }
  if (!grokРазрешён()) {
    console.warn('[Grok] пропущен: НЕ РАЗРЕШЁН — нет GROK_РАЗРЕШЁН=1 в окружении');
    return null;
  }
  if (!(await потолокНеИсчерпан())) return null;

  /**
   * 🔴 ОБРЕЗКА ИСТОРИИ ДЛЯ ПЛАТНОГО ПОСТАВЩИКА. Добавлено 13.09.2026 по
   * живому замеру, который опроверг мой же расчёт двумя часами раньше.
   *
   * ЧТО ПОКАЗАЛ ЖУРНАЛ БОЕВОГО:
   *
   *     [Grok] grok-4.6: ответил, токенов 184969
   *
   * Сто восемьдесят пять тысяч токенов за ОДИН ответ. В комментарии выше я
   * написала «~5000 токенов входа, ≈ $0.016 за ответ» — и ошиблась в
   * двадцать три раза. Настоящая цена такого ответа ≈ $0.37, а потолок в 30
   * вызовов означал бы не $0.48 в сутки, а около $11 — больше, чем всего
   * кредитов на счету ($7.14).
   *
   * ПОЧЕМУ ТАК ВЫШЛО: в запрос уходит ВСЯ память человека целиком. Для
   * бесплатных Gemini это было безразлично, и привычка не считать объём
   * переехала на платный канал вместе с кодом.
   *
   * ЧТО ДЕЛАЕМ: платному поставщику отправляем системную часть полностью
   * (она задаёт личность) и последние реплики разговора. Память при этом не
   * теряется — она остаётся в базе и в бесплатных каналах; урезается только
   * то, что уходит за деньги.
   *
   * Раздел 24: цена одного срабатывания теперь снова считается, а не
   * предполагается. Замер после правки печатается той же строкой журнала.
   */
  const ПРЕДЕЛ_РЕПЛИК = Number(process.env.GROK_РЕПЛИК_В_ЗАПРОСЕ
    || process.env.GROK_HISTORY_LIMIT || '16');
  /**
   * 🔴 ВТОРОЙ ЗАМЕР ПОКАЗАЛ, ЧТО ПЕРВАЯ ПОЧИНКА ПОЧТИ НЕ ПОМОГЛА.
   *
   * После обрезки реплик журнал дал:
   *
   *     [Grok] история обрезана: 20 реплик → 16 (предел 16)
   *     [Grok] grok-4.6: ответил, токенов 180461
   *
   * Было 184 969, стало 180 461 — экономия 2,4 %. Значит объём сидел НЕ в
   * числе реплик, а в СИСТЕМНОМ блоке: туда вкладывается память человека
   * целиком, и она же составляет почти весь запрос.
   *
   * Урок ровно тот же, что и часом раньше, только с другой стороны: я снова
   * починила по представлению о том, где объём, вместо того чтобы сначала
   * посмотреть, из чего он складывается. Разница в том, что теперь замер был
   * сделан СРАЗУ и ошибка прожила пять минут, а не два часа.
   *
   * Поэтому системная часть тоже получает предел по знакам. Режется ХВОСТ:
   * начало системного промпта задаёт личность и правила, а в конце лежит
   * подтянутая память — её и укорачиваем, оставляя самое свежее.
   */
  const ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ = Number(process.env.GROK_SYSTEM_CHAR_LIMIT || '24000');
  const системные = messages
    .filter((m) => m.role === 'system')
    .map((m) => {
      const текст = String(m.content || '');
      if (текст.length <= ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ) return m;
      const голова = Math.floor(ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ * 0.4);
      const хвост = ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ - голова;
      console.warn(`[Grok] системный блок урезан для платного канала: `
        + `${текст.length} → ${ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ} знаков; память в базе цела`);
      return {
        ...m,
        content: текст.slice(0, голова)
          + '\n\n[…часть памяти опущена только для этого платного запроса; '
          + 'в базе она цела и полностью доступна бесплатным каналам…]\n\n'
          + текст.slice(-хвост),
      };
    });
  const разговорные = messages.filter((m) => m.role !== 'system');
  const обрезанные = разговорные.length > ПРЕДЕЛ_РЕПЛИК
    ? разговорные.slice(-ПРЕДЕЛ_РЕПЛИК)
    : разговорные;
  const кЗапросу = [...системные, ...обрезанные];
  if (разговорные.length > обрезанные.length) {
    console.warn(`[Grok] история обрезана для платного канала: `
      + `${разговорные.length} реплик → ${обрезанные.length} `
      + `(предел ${ПРЕДЕЛ_РЕПЛИК}); память в базе не тронута`);
  }

  for (const модель of ЛЕСТНИЦА_GROK) {
    try {
      const ответ = await fetch('https://api.x.ai/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${к}`,
        },
        body: JSON.stringify({
          model: модель,
          messages: кЗапросу,
          max_tokens: maxTokens,
          temperature,
        }),
      });

      if (!ответ.ok) {
        const тело = await ответ.text().catch(() => '');
        console.warn(`[Grok] ${модель}: HTTP ${ответ.status} ${тело.slice(0, 200)}`);
        continue;
      }

      const данные = await ответ.json();
      const текст = данные?.choices?.[0]?.message?.content;
      if (typeof текст !== 'string' || !текст) {
        console.warn(`[Grok] ${модель}: успех, но ПУСТОЙ ответ — `
          + `finish_reason=${данные?.choices?.[0]?.finish_reason || 'не назван'}`);
        continue;
      }

      /**
       * УЧЁТ. Пишем токены, названные самим x.ai, а не нашу оценку по длине
       * строки: раздел 11 требует замера, а не рассуждения. Учёт никогда не
       * роняет ответ — человек важнее строки в таблице.
       */
      try {
        const u = данные?.usage || {};
        const токены =
          Number(u.total_tokens || 0) ||
          Number(u.prompt_tokens || 0) + Number(u.completion_tokens || 0);
        const единиц = токены > 0 ? токены : текст.length;
        const { record } = await import('./cost-guard');
        await record(токены > 0 ? СЛУЖБА : 'grok-chat-chars', единиц, 1);
        console.warn(`[Grok] ${модель}: ответил, токенов ${токены || 'не назвал'}`);
      } catch { /* учёт не важнее самого ответа */ }

      return текст;
    } catch (e) {
      console.warn(`[Grok] ${модель} не ответила: ${String(e).slice(0, 200)}`);
      continue;
    }
  }

  console.warn('[Grok] ни одна модель не ответила — ухожу в базу знаний');
  return null;
}
