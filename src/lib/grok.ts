/** Ключ x.ai. Оба имени переменной — исторически в бою стоят оба. */
function ключ(): string | undefined {
  const к = process.env.XAI_API_KEY || process.env.GROK_API_KEY;
  return к && к.trim().length > 0 ? к.trim() : undefined;
}

/**
 * Разрешён ли Grok. Без разрешения модуль не делает ни одного платного вызова.
 *
 * Раздел 13 требует, чтобы платный путь был закрыт ФИЗИЧЕСКИ, а не «мы туда
 * не ходим». Ключ в окружении стоит с июня — значит закрывать должен не он,
 * а отдельное разрешение.
 */
export function grokРазрешён(): boolean {
  if (!ключ()) return false;
  const свой = process.env.GROK_РАЗРЕШЁН || process.env.GROK_ENABLED || '';
  const общий = process.env.РАЗРЕШЕНЫ_ПЛАТНЫЕ_МОДЕЛИ || process.env.ALLOW_PAID_MODELS || '';
  const да = (з: string) => з === '1' || з.toLowerCase() === 'true';
  return да(свой) || да(общий);
}

