/**
 * Маска для персональных данных в журналах.
 *
 * 🔴 ЗАЧЕМ. В журналах ручек входа адрес почты писался открытым текстом — 21
 * место, включая адрес ПРИГЛАСИВШЕГО (то есть заодно раскрывалась и связь между
 * двумя людьми). Журнал — это не «внутреннее»: он уезжает к площадке хостинга,
 * хранится там неделями, доступен всем, у кого есть доступ к проекту, и
 * попадает в выгрузки при разборе сбоев.
 *
 * Мы сами продаём аудит по GDPR — держать при этом открытые адреса в своих же
 * журналах нельзя, и дело не только в неловкости: адрес почты это персональные
 * данные, и хранить их дольше нужного нам никто не разрешал.
 *
 * ЧТО ОСТАЁТСЯ ПОСЛЕ МАСКИ. Ровно то, что нужно для разбора сбоя: видно, что
 * это разные люди (по устойчивому отпечатку), виден домен (почти все беды с
 * доставкой писем — доменные: то Gmail придирается, то корпоративный сервер
 * молчит), видна первая буква. Восстановить сам адрес по этому нельзя.
 *
 *   `maksim@gmail.com`     → `m***@gmail.com#4f2a`
 *   `a@corp.example`       → `a***@corp.example#91be`
 *
 * Отпечаток берётся от адреса С СОЛЬЮ, иначе по короткому хешу адрес
 * подбирается за секунды: список распространённых адресов невелик.
 */
import crypto from 'crypto';

/**
 * Соль отпечатка.
 *
 * Порядок: сначала ОТДЕЛЬНАЯ соль `LOG_HASH_SALT`, и только если её нет —
 * секрет подписи сессий.
 *
 * Почему именно так. Раньше порядок был обратным, и солью всегда служил ключ,
 * которым подписаны куки входа. Дыры в этом нет — HMAC ключ по своим выходам не
 * выдаёт, — но один и тот же секрет работал на две разные задачи сразу, а это
 * плохая привычка: в день, когда ключ подписи придётся сменить, разом поменяются
 * и все отпечатки в журналах, и связь с прежними записями оборвётся без всякой
 * на то причины.
 *
 * Смена порядка НИЧЕГО не меняет сегодня: `LOG_HASH_SALT` не задан, значит
 * берётся тот же секрет и отпечатки остаются прежними. Но как только отдельная
 * соль появится, она возьмёт верх сама, без правки кода.
 *
 * Если нет ни того ни другого — отпечаток не считается вовсе: лучше журнал без
 * отпечатка, чем отпечаток, по которому адрес подбирается перебором.
 */
const СОЛЬ = process.env.LOG_HASH_SALT || process.env.AIFA_SESSION_SECRET || '';

/** Короткий устойчивый отпечаток — чтобы отличать людей, не называя их. */
function отпечаток(значение: string): string {
  if (!СОЛЬ) return '';
  return (
    '#' +
    crypto.createHmac('sha256', СОЛЬ).update(значение).digest('hex').slice(0, 4)
  );
}

/** Маскирует адрес почты для журнала. Пустое и нестроковое отдаёт как «—». */
export function маскаПочты(адрес: unknown): string {
  if (typeof адрес !== 'string' || !адрес.trim()) return '—';
  const чистый = адрес.trim().toLowerCase();
  const собака = чистый.lastIndexOf('@');
  // Не адрес вовсе (или адрес без домена) — не гадаем, отдаём только отпечаток:
  // писать такое в журнал открытым текстом тем более незачем.
  if (собака <= 0) return '***' + отпечаток(чистый);
  const имя = чистый.slice(0, собака);
  const домен = чистый.slice(собака + 1);
  return `${имя[0]}***@${домен}${отпечаток(чистый)}`;
}

/** То же для произвольной строки с личными данными (имя, ник, телефон). */
export function маскаЛичного(значение: unknown): string {
  if (typeof значение !== 'string' || !значение.trim()) return '—';
  const ч = значение.trim();
  return `${ч[0]}***${отпечаток(ч.toLowerCase())}`;
}
