/** Адрес воркера-посредника. Меняется переменной, чтобы не трогать код. */
const АДРЕС_ПО_УМОЛЧАНИЮ = 'https://aifa-workers-ai.codeeternal.workers.dev';

/**
 * Лестница моделей внутри самого Cloudflare, от лучшей к запасной.
 *
 * Порядок задан замером 16.09.2026, а не размером модели. Имена сверены с
 * живыми вызовами: каждая из трёх отвечала в прогоне. Модель
 * `llama-3.1-8b-instruct`, стоявшая в воркере по умолчанию, СНЯТА
 * Cloudflare 30.05.2026 — вызов отдаёт код 5028. Имя оставлено в этом
 * комментарии как напоминание: модель не исчезает из документации, она
 * просто перестаёт отвечать, и ступень теряется молча.
 */
const ЛЕСТНИЦА_CLOUDFLARE = [
  '@cf/qwen/qwen2.5-coder-32b-instruct',
  '@cf/meta/llama-4-scout-17b-16e-instruct',
  '@cf/mistralai/mistral-small-3.1-24b-instruct',
];

/**
 * 🔴 ПРЕДЕЛ СИСТЕМНОГО БЛОКА ЗДЕСЬ СВОЙ И МЕНЬШЕ, ЧЕМ У OLLAMA.
 *
 * У Ollama стоит 160 000 знаков — и это верно для неё: окно моделей там
 * кратно больше. У `qwen2.5-coder-32b` окно 32 768 токенов НА ВСЁ, включая
 * ответ. Русский текст идёт примерно по 2,5 знака на токен, значит 160 000
 * знаков — это около 64 000 токенов, вдвое больше всего окна.
 *
 * Отправить столько — не «ответ хуже», а отказ либо молча обрезанный
 * моделью вход, при котором пропадает СЕРЕДИНА системного блока. Ровно на
 * этом 14.09.2026 канон базы знаний не доходил до модели ни разу, и со
 * стороны это выглядело как «AIfa опять выдумывает».
 *
 * 60 000 знаков ≈ 24 000 токенов входа, остаток окна остаётся под ответ.
 */
const ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ = Number(
  process.env.CLOUDFLARE_AI_SYSTEM_CHAR_LIMIT || '60000',
);

/** Сколько ждать ответа. Дольше — человек в чате видит пустоту. */
const ТАЙМАУТ_МС = Number(process.env.CLOUDFLARE_AI_TIMEOUT_MS || '45000');

function урезатьСистемный(
  messages: Array<{ role: string; content: string }>,
): Array<{ role: string; content: string }> {
  return messages.map((m) => {
    if (m.role !== 'system') return m;
    const текст = String(m.content || '');
    if (текст.length <= ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ) return m;
    const голова = Math.floor(ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ * 0.4);
    const хвост = ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ - голова;
    console.warn(`[CloudflareAI] системный блок урезан: ${текст.length} → `
      + `${ПРЕДЕЛ_ЗНАКОВ_СИСТЕМЫ} знаков; память в базе цела`);
    return {
      ...m,
      content: текст.slice(0, голова)
        + '\n\n[…часть памяти опущена только для этого запроса; '
        + 'в базе она цела…]\n\n'
        + текст.slice(-хвост),
    };
  });
}

/** Настроена ли ступень. Без секрета воркер отвечает 403 — не стучимся зря. */
export function cloudflareAiНастроен(): boolean {
  return Boolean((process.env.CLOUDFLARE_AI_KEY || '').trim());
}

/**
 * Один ответ от Cloudflare Workers AI или null, если не вышло.
 *
 * null значит «иди дальше по лестнице» — так же ведут себя Ollama, Bedrock и
 * Vertex. Исключение здесь оборвало бы разговор человека вместо перехода к
 * следующей ступени.
 *
 * Каждый отказ печатается с КОДОМ и телом ответа. Молчащий отказ — самый
 * дорогой вид поломки: 14.09.2026 сутки ушли на поиск причины, по которой
 * Bedrock «просто не отвечал», и ответ лежал в одной строке, которую никто
 * не печатал.
 */
export async function cloudflareAiChatCompletion(
  messages: Array<{ role: string; content: string }>,
  maxTokens: number = 4096,
  temperature: number = 0.8,
  modelOverride?: string,
): Promise<string | null> {
  const ключ = (process.env.CLOUDFLARE_AI_KEY || '').trim();
  if (!ключ) {
    console.warn('[CloudflareAI] пропущен: CLOUDFLARE_AI_KEY не задан');
    return null;
  }
  const адрес = (process.env.CLOUDFLARE_AI_URL || АДРЕС_ПО_УМОЛЧАНИЮ).trim();

  const готовые = урезатьСистемный(messages);
  const модели = modelOverride ? [modelOverride] : ЛЕСТНИЦА_CLOUDFLARE;

  for (const модель of модели) {
    const начало = Date.now();
    const прерыватель = new AbortController();
    const будильник = setTimeout(() => прерыватель.abort(), ТАЙМАУТ_МС);
    try {
      const ответ = await fetch(адрес, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-AIfa-Key': ключ,
          // Cloudflare отбрасывает запросы без User-Agent кодами 1010 и 403 —
          // проверено живым вызовом 16.09.2026. Заголовок обязателен.
          'User-Agent': 'AIfa/1.0 (+https://codeofdigitaleternity.com)',
        },
        body: JSON.stringify({
          messages: готовые,
          model: модель,
          max_tokens: maxTokens,
          temperature,
        }),
        signal: прерыватель.signal,
      });

      if (!ответ.ok) {
        const тело = await ответ.text().catch(() => '');
        console.warn(`[CloudflareAI] ${модель}: HTTP ${ответ.status} `
          + `за ${Date.now() - начало} мс — ${тело.slice(0, 300)}`);
        continue;
      }

      const данные = await ответ.json() as {
        ok?: boolean;
        response?: unknown;
        error?: string;
      };

      if (данные.ok === false) {
        console.warn(`[CloudflareAI] ${модель}: воркер вернул отказ — `
          + String(данные.error || '').slice(0, 300));
        continue;
      }

      /**
       * Ответ приходит двумя разными формами, и это не прихоть воркера.
       * Обычные модели отдают строку в поле `response`; модели семейства
       * gpt-oss отдают структуру `choices[0].message.content`. Разбор
       * обеих форм стоит четырёх строк, а его отсутствие превратило бы
       * рабочий ответ в «[object Object]» в окне чата.
       */
      let текст: string | null = null;
      const сырое = данные.response;
      if (typeof сырое === 'string') {
        текст = сырое;
      } else if (сырое && typeof сырое === 'object') {
        const о = сырое as {
          response?: string;
          choices?: Array<{ message?: { content?: string } }>;
        };
        текст = о.choices?.[0]?.message?.content ?? о.response ?? null;
      }

      if (текст && текст.trim()) {
        console.warn(`[CloudflareAI] ответила ${модель} `
          + `за ${Date.now() - начало} мс, ${текст.length} знаков`);
        (globalThis as { __ктоОтветил?: string }).__ктоОтветил =
          'cloudflare/' + модель.split('/').pop();
        return текст.trim();
      }

      console.warn(`[CloudflareAI] ${модель}: пустой ответ — иду к следующей`);
    } catch (err) {
      const причина = String(err).slice(0, 200);
      const этоТаймаут = причина.includes('abort');
      console.warn(`[CloudflareAI] ${модель}: `
        + (этоТаймаут ? `молчала дольше ${ТАЙМАУТ_МС} мс` : причина));
    } finally {
      clearTimeout(будильник);
    }
  }

  return null;
}
