/**
 * ОТЛОЖЕННАЯ ПУБЛИКАЦИЯ НОВОСТЕЙ.
 *
 * 🔴 ЗАЧЕМ. Статьи хранятся с датой в поле `date` (ДД.ММ.ГГГГ), и до 08.08.2026
 * эта дата была ровно подписью — списки и карта сайта отдавали ВСЁ, что лежит в
 * файле. То есть статья, подготовленная к будущей дате, появлялась на сайте в ту
 * же секунду, как её добавили: и в списке, и в поиске, и в ленте подписки.
 *
 * Мы как раз готовим материал заранее — значит нужна отсечка. Она здесь.
 *
 * КАК СЧИТАЕТСЯ ДЕНЬ. По UTC, и это не мелочь: у нас уже была беда, когда одна
 * часть кода считала дату по местному времени, а другая по UTC, и рассылка
 * уходила со вчерашним числом. Один источник времени — один день.
 *
 * Статья с датой сегодня показывается сразу, с завтрашней — нет.
 */

interface СДатой {
  date?: string;
  /**
   * Ручной выпуск раньше своей даты.
   *
   * Отсечка по дате защищает ВСЕ подготовленные материалы разом, и ломать её
   * ради одной статьи нельзя. Но иногда материал нужно показать сегодня, оставив
   * в подписи завтрашнюю дату — это «новость из будущего», и дата в ней часть
   * замысла, а не опечатка.
   *
   * Поле действует только на ту статью, где оно проставлено; на остальные
   * расписание работает как прежде.
   */
  published?: boolean;
}

/** «12.08.2026» → 20260812. Непонятная дата даёт 0, то есть статья считается старой. */
function вЧисло(дата: string | undefined): number {
  const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(String(дата || ''));
  return m ? Number(`${m[3]}${m[2]}${m[1]}`) : 0;
}

function сегодняUTC(): number {
  const д = new Date();
  const мм = String(д.getUTCMonth() + 1).padStart(2, '0');
  const дд = String(д.getUTCDate()).padStart(2, '0');
  return Number(`${д.getUTCFullYear()}${мм}${дд}`);
}

/**
 * Оставляет только вышедшие статьи.
 *
 * `NEWS_SHOW_SCHEDULED=1` показывает и будущие — этим удобно посмотреть
 * подготовленный материал на предпросмотре, не открывая его всем.
 */
export function тольковышедшие<T extends СДатой>(статьи: T[]): T[] {
  if (process.env.NEWS_SHOW_SCHEDULED === '1') return статьи;
  const сегодня = сегодняUTC();
  return статьи.filter((с) => с.published === true || вЧисло(с.date) <= сегодня);
}

/** То же имя латиницей — для мест, где удобнее английский вызов. */
export const publishedOnly = тольковышедшие;
