/**
 * Заслон от обращений во внутреннюю сеть (SSRF).
 *
 * AIfaFocus по замыслу открывает адрес, который ввёл ПОСТОРОННИЙ человек. Значит
 * любой наш сервер, любая служебная ручка и облачная служба метаданных
 * находятся от него на расстоянии одной строчки в поле ввода. Это не
 * теоретический риск, а основной способ, которым ломают сканеры сайтов.
 *
 * Что было до этого файла:
 *
 *   const host = parsed.hostname.toLowerCase();
 *   const isPrivateIp = host.startsWith('10.') || host.startsWith('192.168.') || …
 *
 * Проверялось НАПИСАНИЕ имени, а не то, куда оно разрешается. Дыры:
 *
 *   1. Имя, разрешающееся во внутренний адрес. `localtest.me` указывает на
 *      127.0.0.1, `169.254.169.254.nip.io` — на службу метаданных. Обе строки
 *      проходят проверку написания, потому что выглядят как обычные домены.
 *   2. Адреса из КАРТЫ САЙТА. Их брали у проверяемого сайта и открывали, вообще
 *      не проверяя: достаточно положить в свой sitemap.xml ссылку на
 *      http://169.254.169.254/ — и мы сходим туда сами.
 *   3. Неполный перечень диапазонов: 127.0.0.2 (весь 127/8), 100.64/10,
 *      0.0.0.0/8, IPv6 (::1, fc00::/7, fe80::/10) и записи вида ::ffff:127.0.0.1.
 *
 * Здесь закрыты все три. Проверка идёт по РАЗРЕШЁННОМУ адресу, а не по имени.
 *
 * Правило при сбое разрешения имени: ПРОПУСКАЕМ. Если имя не разрешается, то и
 * запрос по нему не пройдёт — отказывать тут значит ломать проверку живых
 * сайтов ради случая, которого не существует.
 */
import { promises as dns } from 'node:dns';

/** IPv4 во внутренних диапазонах. Список полный, а не «основные три». */
function частныйIPv4(ip: string): boolean {
  const ч = ip.split('.').map(Number);
  if (ч.length !== 4 || ч.some((n) => !Number.isInteger(n) || n < 0 || n > 255)) return false;
  const [a, b] = ч;
  if (a === 0) return true;                       // 0.0.0.0/8 — «этот хост»
  if (a === 10) return true;                      // 10/8
  if (a === 127) return true;                     // весь 127/8, не только 127.0.0.1
  if (a === 169 && b === 254) return true;        // 169.254/16 — метаданные облака
  if (a === 172 && b >= 16 && b <= 31) return true;
  if (a === 192 && b === 168) return true;
  if (a === 192 && b === 0) return true;          // 192.0.0/24 и 192.0.2/24
  if (a === 100 && b >= 64 && b <= 127) return true; // 100.64/10 — сети операторов
  if (a === 198 && (b === 18 || b === 19)) return true;
  if (a >= 224) return true;                      // многоадресные и служебные
  return false;
}

/** IPv6, включая запись IPv4 внутри IPv6 (::ffff:127.0.0.1). */
function частныйIPv6(ip: string): boolean {
  const н = ip.toLowerCase().replace(/^\[|\]$/g, '');
  if (н === '::' || н === '::1') return true;
  const вложенный = н.match(/::ffff:(\d+\.\d+\.\d+\.\d+)$/);
  if (вложенный) return частныйIPv4(вложенный[1]);
  if (/^f[cd]/.test(н)) return true;              // fc00::/7 — внутренние
  if (/^fe[89ab]/.test(н)) return true;           // fe80::/10 — локальные для канала
  if (/^ff/.test(н)) return true;                 // многоадресные
  return false;
}

export function частныйАдрес(ip: string): boolean {
  return ip.includes(':') ? частныйIPv6(ip) : частныйIPv4(ip);
}

/**
 * Проверяет, куда РАЗРЕШАЕТСЯ имя. Возвращает true, если ходить туда можно.
 *
 * Разрешение имени делается один раз и с коротким сроком ожидания: заслон не
 * должен превращаться в способ подвесить наш сервер длинным ответом чужого
 * сервера имён.
 */
export async function хостБезопасен(hostname: string): Promise<boolean> {
  const имя = hostname.toLowerCase().replace(/^\[|\]$/g, '');

  // Имя записано сразу адресом — разрешать нечего, проверяем как есть.
  if (/^[\d.]+$/.test(имя) || имя.includes(':')) return !частныйАдрес(имя);

  // Служебные имена облаков. Разрешаются только изнутри, но спросить о них
  // могут откуда угодно, и отказ здесь ничего не стоит.
  if (имя === 'localhost' || имя.endsWith('.localhost') || имя.endsWith('.internal')
      || имя.endsWith('.local') || имя === 'metadata.google.internal') return false;

  try {
    const адреса = await Promise.race([
      dns.lookup(имя, { all: true }),
      new Promise<never>((_, откл) => setTimeout(() => откл(new Error('срок вышел')), 4000)),
    ]);
    if (!адреса.length) return true;              // ничего не узнали — пропускаем
    return !адреса.some((а) => частныйАдрес(а.address));
  } catch {
    return true;                                  // имя не разрешилось — пропускаем
  }
}

/**
 * Проверяет ЧУЖОЙ адрес, взятый не от посетителя, а со стороннего сайта — из
 * карты сайта, из ссылки, из перенаправления.
 *
 * Кроме внутренних адресов отсекает: не-HTTP схемы (file:, gopher:, data:) и
 * чужое происхождение. Второе важно не только для безопасности: AIfaFocus обещает
 * проверить ОДИН сайт, а не тот, на который его владелец решил нас увести.
 */
export async function ссылкаБезопасна(адрес: string, ожидаемоеПроисхождение?: string): Promise<boolean> {
  let разобранный: URL;
  try { разобранный = new URL(адрес); } catch { return false; }
  if (разобранный.protocol !== 'http:' && разобранный.protocol !== 'https:') return false;
  if (ожидаемоеПроисхождение && разобранный.origin !== ожидаемоеПроисхождение) return false;
  return хостБезопасен(разобранный.hostname);
}
