/**
 * Готовая строка реквизитов для правовых страниц и подвала.
 * Незаполненные поля пропускаются — на сайт не попадает пустая строка.
 */
export function строкаРеквизитов(язык: Язык): string {
  const п = ПОДПИСИ[язык] ?? ПОДПИСИ.en;
  const части: string[] = [
    `${РЕКВИЗИТЫ.имя[язык] ?? РЕКВИЗИТЫ.имя.en} — ${РЕКВИЗИТЫ.статус[язык] ?? РЕКВИЗИТЫ.статус.en}`,
  ];
  if (РЕКВИЗИТЫ.правоваяФорма) части.push(`${п.form}: ${РЕКВИЗИТЫ.правоваяФорма}`);
  if (РЕКВИЗИТЫ.страна) части.push(`${п.country}: ${РЕКВИЗИТЫ.страна}`);
  if (РЕКВИЗИТЫ.адрес) части.push(`${п.address}: ${РЕКВИЗИТЫ.адрес}`);
  if (РЕКВИЗИТЫ.регистрационныйНомер) части.push(`${п.reg}: ${РЕКВИЗИТЫ.регистрационныйНомер}`);
  if (РЕКВИЗИТЫ.налоговыйНомер) части.push(`${п.tax}: ${РЕКВИЗИТЫ.налоговыйНомер}`);
  if (РЕКВИЗИТЫ.номерНДС) части.push(`${п.vat}: ${РЕКВИЗИТЫ.номерНДС}`);
  if (РЕКВИЗИТЫ.телефон) части.push(`${п.phone}: ${РЕКВИЗИТЫ.телефон}`);
  части.push(`${п.email}: ${РЕКВИЗИТЫ.почта}, ${РЕКВИЗИТЫ.почтаПоддержки}, ${РЕКВИЗИТЫ.почтаПродаж}`);
  return части.join(' · ');
}
