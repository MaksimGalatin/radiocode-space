/**
 * Читаемый вариант акцентного цвета станции — ТОЛЬКО для текста.
 *
 * ЧТО БЫЛО СЛОМАНО (молча, без единой ошибки в консоли):
 * подписи жанра на карточках станций и бегущая строка рисовались акцентным
 * цветом станции с искусственно приглушённой прозрачностью — `${color}80`
 * (50%) и `${color}50` (31%). На фоне #0c0c12 это давало замеренный контраст
 * 1.73 для фиолетовой станции, 1.92 для красной, 2.16 для бегущей строки при
 * норме WCAG AA 4.5. Текст физически присутствовал в DOM, все проверки
 * «страница отрисовалась» проходили, но глазом надписи почти не читались —
 * ровно та жалоба, что «не видно ничего».
 *
 * ПОЧЕМУ НЕЛЬЗЯ ПРОСТО УБРАТЬ ПРОЗРАЧНОСТЬ: у фиолетового #B000FF даже при
 * 100% непрозрачности контраст на #0c0c12 равен 3.98 — всё ещё ниже 4.5,
 * потому что у чистого фиолетового низкая относительная яркость (в формуле
 * WCAG зелёный канал весит 0.7152, а у #B000FF он нулевой).
 *
 * ПОЭТОМУ: для текста берём осветлённый двойник только тех акцентов, что не
 * дотягивают сами. Заливки, рамки, свечения и полосы эквалайзера продолжают
 * использовать исходный station.color — фирменный вид не меняется.
 *
 * Замеры (текст на самом светлом из встречающихся фонов карточки #0c0c12):
 *   #00F0FF  циан      13.80 — оставляем как есть
 *   #39FF14  зелёный   16.30 — оставляем как есть
 *   #FF003C  красный    4.94 — оставляем как есть (достаточно на 100%)
 *   #B000FF  фиолет     3.98 → #C77DFF даёт 7.25
 */

/** Акценты, которые при 100% непрозрачности всё равно не проходят 4.5. */
const ОСВЕТЛЁННЫЕ: Record<string, string> = {
  '#b000ff': '#C77DFF',
};

/**
 * Возвращает цвет, которым безопасно писать текст поверх тёмного фона сайта.
 *
 * Годится и для обратного случая — заливки кнопки, на которой лежит ТЁМНАЯ
 * надпись: причина провала там та же (низкая яркость чистого фиолетового),
 * поэтому и лечение то же. На /station/boa-506 кнопка «▶ Listen now» с
 * тёмным текстом на заливке #B000FF давала 4.14; на #C77DFF — 7.53.
 *
 * Неизвестные цвета возвращаются без изменений — функция ничего не ломает,
 * если в stations.ts появится новая станция.
 */
export function readableAccent(color: string): string {
  if (!color) return color;
  return ОСВЕТЛЁННЫЕ[color.trim().toLowerCase()] ?? color;
}
