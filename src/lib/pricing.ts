/** Строка о партнёрском тарифе — под карточками, одной фразой. */
export function партнёрскийСтрокой(язык: string = 'en'): string {
  return ПАРТНЁРСКИЙ.описание[язык] ?? ПАРТНЁРСКИЙ.описание.en;
}

export function тарифПоКоду(код: КодТарифа): Тариф {
  const т = ТАРИФЫ.find((x) => x.код === код);
  if (!т) throw new Error(`неизвестный тариф: ${код}`);
  return т;
}

/** Цена одной строкой: «Spark ($15/mo)» / «Цифровая ДНК ($1 000 разово за устройство, далее $200/мес)». */
export function ценаСтрокой(код: КодТарифа, язык: string = 'en'): string {
  const т = тарифПоКоду(код);
  const имя = т.название[язык] ?? т.название.en;
  const вМес = язык === 'ru' ? `$${т.вМесяц}/мес` : язык === 'es' ? `$${т.вМесяц}/mes` : язык === 'zh' ? `$${т.вМесяц}/月` : `$${т.вМесяц}/mo`;
  if (!т.разово) return `${имя} (${вМес})`;
  const пояснение = т.разовоПояснение?.[язык] ?? т.разовоПояснение?.en ?? '';
  const далее = язык === 'ru' ? 'далее' : язык === 'es' ? 'luego' : язык === 'zh' ? '之后' : 'then';
  return `${имя} ($${т.разово.toLocaleString('en-US')} ${пояснение}, ${далее} ${вМес})`;
}

/** Все тарифы одной строкой — для правовых документов. */
export function всеЦеныСтрокой(язык: string = 'en'): string {
  return ТАРИФЫ.map((т) => ценаСтрокой(т.код, язык)).join('; ');
}
