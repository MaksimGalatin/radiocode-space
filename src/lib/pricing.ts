/**
 * ЦЕНЫ — ОДИН ИСТОЧНИК НА ВСЮ ЭКОСИСТЕМУ.
 *
 * До этого модуля тарифы жили в трёх местах и ни одно не было связано с
 * другими кодом:
 *
 *   1. кабинет, вкладка тарифов (`app/cabinet/TiersTab.tsx`) — то, что человек
 *      видит и по чему принимает решение;
 *   2. Дополнение A4 к Условиям (`legal/addendum.tsx`) — то, что он юридически
 *      принимает;
 *   3. публичная оферта (`app/service-agreement/page.tsx`) — то, по чему
 *      заключается договор на разовые работы.
 *
 * Цена, изменённая в одном месте, молча расходилась с двумя другими. Обнаружить
 * это можно было только чтением всех трёх документов подряд, а заметил бы —
 * человек, увидевший в договоре не ту сумму, что в кабинете.
 *
 * Теперь сумма живёт здесь и подставляется во все три места. Расходиться нечему.
 *
 * Значения взяты из Конституции экосистемы, раздел 5 «Тарифная сетка», и сверены
 * с тем, что показывал кабинет на 11.08.2026.
 */

