'use client';

/**
 * ЯЗЫК, ОПРЕДЕЛЁННЫЙ НА СЕРВЕРЕ.
 *
 * 🔴 ЗАЧЕМ ЭТОТ ФАЙЛ. Замер 09.08.2026: `radiocode.space/?lang=ru`,
 * `?lang=es` и `?lang=zh` отдавали ПОБАЙТОВО ту же страницу, что и адрес без
 * метки, — английскую. Поисковик и любой, кто смотрит исходный текст страницы,
 * видели один язык из четырёх. Правило Четырёх Сайтов при этом требует, чтобы
 * четвёртый сайт был на тех же четырёх языках, что и остальные три.
 *
 * ПОЧЕМУ ТАК ВЫХОДИЛО. Выбранный язык лежит в хранилище zustand с сохранением
 * в браузере (`persist`). На сервере браузерного хранилища нет, поэтому при
 * отрисовке всегда бралось начальное значение — `en`. Русский текст появлялся
 * только после того, как страница доедет до браузера и оживёт. Для человека
 * это мелькание, для поисковика — отсутствие трёх языков.
 *
 * 🔴 ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ЗАПИСАТЬ ЯЗЫК В ХРАНИЛИЩЕ НА СЕРВЕРЕ. Хранилище
 * zustand — одиночка на уровне модуля. На сервере оно одно на ВЕСЬ процесс, а
 * значит общее для всех запросов сразу. Записав туда язык одного посетителя,
 * мы отдали бы его язык всем остальным, кто попал на тот же процесс. Это не
 * теоретическая опасность, а обычная утечка состояния между запросами.
 *
 * КАК СДЕЛАНО ВМЕСТО ЭТОГО. Контекст React живёт ровно один запрос и никуда не
 * протекает. Раскладка кладёт в него язык, вычисленный из заголовка `x-locale`
 * (его ставит middleware по метке `?lang=`), а хук ниже решает, чьё слово
 * главнее:
 *
 *   • пока хранилище браузера не ожило — язык с сервера. Первая отрисовка в
 *     браузере совпадает с серверной, и React не ругается на расхождение;
 *   • как только хранилище ожило — выбор человека, сделанный раньше.
 *
 * Порядок именно такой: сервер знает про адрес, но не знает про прежний выбор;
 * браузер знает про выбор. Пока второй молчит, слушаем первого.
 */

import React, { createContext, useContext } from 'react';
import { useLang, type Lang } from '@/lib/i18n';

const КонтекстЯзыка = createContext<Lang>('en');

export function ЯзыкССервера({ язык, children }: { язык: Lang; children: React.ReactNode }) {
  return <КонтекстЯзыка.Provider value={язык}>{children}</КонтекстЯзыка.Provider>;
}

/**
 * Единственное место, где решается, какой язык показывать.
 *
 * Возвращает язык человека, если браузер уже вспомнил его выбор, и язык из
 * адреса — пока не вспомнил. Никогда не возвращает пустое: у контекста есть
 * значение по умолчанию.
 */
export function useЯзык(): Lang {
  const сСервера = useContext(КонтекстЯзыка);
  const сохранённый = useLang((s: { lang: Lang }) => s.lang);
  const ожил = useLang((s: { _hasHydrated: boolean }) => s._hasHydrated);
  return (ожил ? сохранённый : сСервера) || 'en';
}
