function buildCsp(nonce: string): string {
  return [
    "default-src 'self'",
    // GA4 грузится с googletagmanager.com — без него политика молча режет тег
    // и сайт исчезает из аналитики.
    `script-src 'self' 'nonce-${nonce}' 'unsafe-inline' https://accounts.google.com https://apis.google.com https://www.googletagmanager.com https://va.vercel-scripts.com https://vercel.live`,
    // Оформление (было F3). Раздельно и намеренно:
    //   • style-src-attr — атрибут style="…" на элементе; их сотни (так работают
    //     инлайновые стили React), поэтому 'unsafe-inline' здесь остаётся;
    //   • style-src-elem — блоки <style> и таблицы стилей; 'unsafe-inline' убран.
    //     Все наши блоки <style> вынесены в обычные .css-файлы, поэтому подставить
    //     в страницу чужое оформление больше нельзя. Через такой блок воруют
    //     данные: селектор по атрибуту плюс фоновая картинка отдают введённое
    //     значение на чужой сервер, без единой строчки скрипта.
    // ⚠️ Добавишь новый <style> в разметке — он молча не применится. Заводи .css.
    //    Это же касается components/ui/chart.tsx: он сейчас НИГДЕ не используется,
    //    но строит стили на лету — при первом же применении его надо переделать.
    // style-src оставлен как раньше: браузеры без раздельных директив получают
    // прежний уровень вместо сломанной страницы.
    "style-src 'self' 'unsafe-inline' https://accounts.google.com",
    `style-src-elem 'self' 'nonce-${nonce}' https://accounts.google.com`,
    "style-src-attr 'unsafe-inline'",
    // Картинки. Единственный <img> во всём приложении — аватар паспорта, и он
    // приходит строкой data: (src/app/api/passport/route.ts прямо проверяет,
    // что значение начинается с `data:image/`). Всё остальное лежит в /public,
    // то есть подпадает под 'self'. Адреса Google оставлены с запасом: кнопка
    // входа рисуется их библиотекой, и если она когда-нибудь снова начнёт
    // подтягивать значок с gstatic, кнопка не превратится в пустое место.
    `img-src 'self' data: blob: https://lh3.googleusercontent.com https://*.googleusercontent.com https://ssl.gstatic.com https://www.gstatic.com ${AUDIO_HOSTS}`,
    `media-src 'self' blob: ${AUDIO_HOSTS}`,
    // Куда странице разрешено СТУЧАТЬСЯ. Здесь схема `https:` была опаснее
    // всего: она разрешала выгрузку данных на любой сервер. Перечислено
    // поимённо:
    //   • 'self' — все наши /api/*;
    //   • accounts.google.com — вход через Google;
    //   • google-analytics/googletagmanager — счётчик GA4 из src/app/layout.tsx;
    //   • va.vercel-scripts.com и vitals.vercel-insights.com — @vercel/analytics;
    //   • vercel.live — панель отзывов, она появляется только на предпросмотрах;
    //   • адреса звука — см. AUDIO_HOSTS выше (SaveButton качает трек сам).
    `connect-src 'self' https://accounts.google.com https://www.google-analytics.com https://*.google-analytics.com https://analytics.google.com https://*.analytics.google.com https://www.googletagmanager.com https://va.vercel-scripts.com https://vitals.vercel-insights.com https://vercel.live wss://vercel.live ${AUDIO_HOSTS}`,
    "font-src 'self' data:",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "frame-src 'self' https://accounts.google.com",
    "object-src 'none'",
    "base-uri 'self'",
    "frame-ancestors 'self'",
    'upgrade-insecure-requests',
  ].join('; ') + ';';
}

export function middleware(req: NextRequest) {
  // Метка обязана быть непредсказуемой: угаданная метка обесценивает защиту.
  const nonce = btoa(crypto.randomUUID() + crypto.randomUUID()).replace(/=+$/, '');
  const csp = buildCsp(nonce);

  const headers = new Headers(req.headers);
  headers.set('x-nonce', nonce);
  // Next читает метку именно из этого заголовка запроса и сам проставляет её
  // своим служебным скриптам загрузки страницы. Без него страница осталась бы
  // белой: собственные скрипты Next оказались бы запрещены.
  headers.set('Content-Security-Policy', csp);

  // 🔴 ЯЗЫК ЗАПРОСА НЕ ДОХОДИЛ ДО СЕРВЕРА ВООБЩЕ.
  //
  // Метка `?lang=` читалась только в браузере, а сервер о ней не знал — и
  // отдавал одну и ту же английскую страницу на все четыре языка. Замер
  // 09.08.2026: `/?lang=ru`, `/?lang=es` и `/?lang=zh` возвращали побайтово тот
  // же ответ, что и адрес без метки.
  //
  // Пробрасываем язык заголовком — ровно так же, как это сделано на
  // aifa.digital. С ним раскладка ставит верный `<html lang>`, а дальше по
  // этому же признаку страницы смогут отдавать переведённый текст сразу, а не
  // после того, как отработает браузер.
  const метка = req.nextUrl.searchParams.get('lang');
  headers.set('x-locale', ['en', 'ru', 'es', 'zh'].includes(метка || '') ? (метка as string) : 'en');

  const res = NextResponse.next({ request: { headers } });
  res.headers.set('Content-Security-Policy', csp);
  return res;
}

