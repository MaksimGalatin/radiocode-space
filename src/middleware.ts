import { NextRequest, NextResponse } from 'next/server';

/**
 * Политика содержимого с одноразовой меткой.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ. Политика лежала в next.config.ts и разрешала
 * выполнить ЛЮБОЙ встроенный скрипт ('unsafe-inline'). Это сводило её защиту
 * от подстановки чужого кода почти к нулю: скрипт, попавший в страницу через
 * форму, отзыв или чужой виджет, выполнялся бы наравне с нашим. Наш
 * собственный Оракул ставил за это замечание, и ставил справедливо.
 *
 * Статический заголовок из конфигурации метку выдавать не умеет — она обязана
 * быть новой на каждый ответ. Поэтому политика переехала сюда. Держать её в
 * двух местах нельзя: браузер получил бы два заголовка и применял бы оба
 * сразу — строгий и старый слабый.
 *
 * КАК РАБОТАЕТ. На каждый ответ выпускается случайная метка. Она объявляется
 * в политике и проставляется нашим скриптам в src/app/layout.tsx. Скрипт без
 * метки браузер не выполнит, а подставленному извне взять её неоткуда —
 * она новая каждый раз.
 *
 * 'unsafe-inline' оставлен НАМЕРЕННО и вреда не несёт: по стандарту CSP
 * уровня 3 браузер обязан игнорировать его при наличии метки. Он нужен лишь
 * очень старым браузерам, которые меток не понимают, — им достаётся прежний
 * уровень защиты вместо полностью сломанной страницы.
 *
 * Встроенные СТИЛИ остаются разрешёнными: их задают атрибутом style в сотнях
 * мест, а риск там другого порядка — подмена оформления, а не запуск кода.
 *
 * ВАЖНО про Google Sign-In: accounts.google.com обязан быть в script-src
 * (загрузчик gsi/client), frame-src (кнопка и всплывающее окно) и style-src
 * (внедряемые им стили). Без этого политика молча ломает кнопку Google —
 * на этом сайте так уже случалось.
 */
/**
 * 🔴 ИСКЛЮЧЕНИЕ ДЛЯ КАБИНЕТА. Библиотека входа через Google (GSI) вставляет в
 * страницу свой блок <style> примерно на десять тысяч знаков и метку на него не
 * ставит. Со строгой директивой браузер его не применяет, и кнопка входа
 * превращается в гигантский логотип с задвоенной подписью — проверено вживую на
 * предпросмотре (`style.sheet === null`). Поэтому на путях кабинета встроенные
 * блоки остаются разрешёнными, а на всех остальных страницах — запрещены.
 */
function isCabinetPath(pathname: string): boolean {
  return /^(\/(ru|en|es|zh))?\/cabinet(\/|$)/.test(pathname);
}

/**
 * Послабление нужно только на экране входа, то есть пока сессии нет.
 *
 * Кнопка Google рисуется ТОЛЬКО тем, кто ещё не вошёл. Значит и послабление
 * должно действовать ровно до входа. Ценное лежит у ВОШЕДШЕГО — переписка,
 * платежи, данные кабинета; кража через подставленный блок оформления
 * опасна именно после входа. До входа красть нечего.
 *
 * Достоверность куки здесь не проверяется намеренно: это не право доступа,
 * а лишь признак «человек уже вошёл». Подделав куку, злоумышленник сделает
 * политику СТРОЖЕ для самого себя — вреда в этом нет.
 */
function needsGoogleButton(req: NextRequest, pathname: string): boolean {
  return isCabinetPath(pathname) && !req.cookies.get('user_session');
}

function buildCsp(nonce: string): string {
  return [
    "default-src 'self'",
    // GA4 грузится с googletagmanager.com — без него политика молча режет тег
    // и сайт исчезает из аналитики.
    `script-src 'self' 'nonce-${nonce}' 'unsafe-inline' https://accounts.google.com https://apis.google.com https://www.googletagmanager.com https://va.vercel-scripts.com https://vercel.live`,
    // Оформление (было F3). Раздельно и намеренно:
    //   • style-src-attr — атрибут style="…" на элементе; их сотни (так работают
    //     инлайновые стили React), поэтому 'unsafe-inline' здесь остаётся;
    //   • style-src-elem — блоки <style> и таблицы стилей; 'unsafe-inline' убран.
    //     Все наши блоки <style> вынесены в обычные .css-файлы, поэтому подставить
    //     в страницу чужое оформление больше нельзя. Через такой блок воруют
    //     данные: селектор по атрибуту плюс фоновая картинка отдают введённое
    //     значение на чужой сервер, без единой строчки скрипта.
    // ⚠️ Добавишь новый <style> в разметке — он молча не применится. Заводи .css.
    //    Это же касается components/ui/chart.tsx: он сейчас НИГДЕ не используется,
    //    но строит стили на лету — при первом же применении его надо переделать.
    // style-src оставлен как раньше: браузеры без раздельных директив получают
    // прежний уровень вместо сломанной страницы.
    "style-src 'self' 'unsafe-inline' https://accounts.google.com",
    `style-src-elem 'self' 'nonce-${nonce}' https://accounts.google.com`,
    "style-src-attr 'unsafe-inline'",
    "img-src 'self' data: blob: https:",
    "media-src 'self' blob: https:",
    "connect-src 'self' https: wss:",
    "font-src 'self' data:",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "frame-src 'self' https://accounts.google.com",
    "object-src 'none'",
    "base-uri 'self'",
    "frame-ancestors 'self'",
    'upgrade-insecure-requests',
  ].join('; ') + ';';
}

export function middleware(req: NextRequest) {
  // Метка обязана быть непредсказуемой: угаданная метка обесценивает защиту.
  const nonce = btoa(crypto.randomUUID() + crypto.randomUUID()).replace(/=+$/, '');
  const csp = buildCsp(nonce);

  const headers = new Headers(req.headers);
  headers.set('x-nonce', nonce);
  // Next читает метку именно из этого заголовка запроса и сам проставляет её
  // своим служебным скриптам загрузки страницы. Без него страница осталась бы
  // белой: собственные скрипты Next оказались бы запрещены.
  headers.set('Content-Security-Policy', csp);

  const res = NextResponse.next({ request: { headers } });
  res.headers.set('Content-Security-Policy', csp);
  return res;
}

