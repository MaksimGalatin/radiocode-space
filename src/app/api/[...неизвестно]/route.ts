import { NextResponse } from 'next/server';

/**
 * 🔴 ЛОВУШКА ДЛЯ НЕСУЩЕСТВУЮЩИХ РУЧЕК — почему она здесь.
 *
 * Замер 19.08.2026 на всех четырёх сайтах: `/api/zzz-random` отдавал 404 без
 * заголовков и **200 с HTML-страницей**, если в запросе был `Authorization`.
 *
 * Разбор: запрос с заголовком авторизации не берётся из кэша и доходит до
 * приложения. Next не находит маршрут, отдаёт свою страницу «не найдено»
 * (`X-Matched-Path: /_not-found`) — и отдаёт её с кодом 200. Снаружи это
 * выглядит как «ручка существует и отвечает успехом»: любая автоматическая
 * проверка на этом ломается, а наш собственный сканер счёл бы такую ручку
 * живой.
 *
 * Исключение `api/` из прослойки эту беду не лечит: код 200 приходит не от
 * прослойки, а от самого приложения. Лечит только явный обработчик, который
 * ловит всё непойманное внутри `/api/` и отвечает как положено ручке — коротким
 * JSON и кодом 404.
 *
 * Настоящие маршруты имеют приоритет над этим: он срабатывает только там, где
 * ничего другого не нашлось.
 */

const ответ = () =>
  NextResponse.json(
    { error: 'not_found', сообщение: 'Такой ручки нет' },
    { status: 404, headers: { 'Cache-Control': 'no-store' } },
  );

export const GET = ответ;
export const POST = ответ;
export const PUT = ответ;
export const PATCH = ответ;
export const DELETE = ответ;
export const HEAD = ответ;
export const OPTIONS = ответ;
