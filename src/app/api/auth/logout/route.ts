import { NextRequest, NextResponse } from 'next/server';
import { USER_COOKIE } from '@/lib/user-auth';
import { dbRateLimit, clientIp } from '@/lib/rate-limit-db';

export const dynamic = 'force-dynamic';

export async function POST(_req: NextRequest) {
  // Ограничение частоты: наплыв.
  // Счёт ведётся в базе, а не в памяти процесса: счётчик в памяти
  // обнуляется при каждой выкладке и у каждого экземпляра свой,
  // поэтому заявленный предел на деле мягче объявленного.
  const адрес_auth_logout = clientIp(_req as never);
  if (адрес_auth_logout !== 'unknown' && !(await dbRateLimit(`auth_logout:${адрес_auth_logout}`, 30, 60000))) {
    return NextResponse.json({ error: 'Слишком много запросов. Подождите немного.' }, { status: 429 });
  }


  // 🔴 ВЫХОД ОБЕСЦЕНИВАЕТ ВЫДАННЫЙ ТОКЕН, А НЕ ТОЛЬКО СТИРАЕТ КУКУ.
  //
  // Стереть куку у себя — это попросить браузер забыть ключ. Сам ключ при
  // этом остаётся действительным: у кого он списан (снят с чужой машины,
  // вытащен из журнала, сохранён расширением) — тот и войдёт.
  //
  // Замер 20.08.2026: здесь стояло только стирание куки. Человек нажимал
  // «выйти» на чужом компьютере, и его старая кука работала ЕЩЁ ДО 30 СУТОК,
  // отдавая ключ шифрования его памяти. На центральном сайте отзыв был с
  // 25.07.2026, сюда он не доехал.
  //
  // Поднимаем поколение — все ранее выданные токены человека перестают
  // приниматься немедленно и на всех четырёх сайтах сразу: счётчик общий.
  try {
    const { getSessionEmail, поднятьПоколение } = await import('@/lib/user-auth');
    const почта = getSessionEmail(_req);
    if (почта) await поднятьПоколение(почта);
  } catch (err) {
    // База недоступна — куку всё равно стираем, выход не рушим.
    console.warn('[logout] поколение не поднято:', String(err));
  }

  const res = NextResponse.json({ success: true });
  res.cookies.set(USER_COOKIE, '', { httpOnly: true, path: '/', maxAge: 0 });
  // При выходе просим браузер стереть данные этого сайта.
  //
  // Зачем: человек вышел из кабинета на чужом или общем компьютере. Без этого
  // заголовка в хранилище браузера остаются его сведения — кэш страниц,
  // локальное хранилище, остатки сессии. Следующий, кто сядет за этот
  // компьютер, их увидит.
  //
  // Наш собственный AIfaFocus выставлял нам за это замечание PRIV-LOGOUT-001, и
  // выставлял справедливо. Обязательным требованием закона это не является,
  // но стоит одну строку.
  res.headers.set('Clear-Site-Data', '"cache", "cookies", "storage"');
  return res;
}
