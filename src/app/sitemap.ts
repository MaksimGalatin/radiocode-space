const SITE = 'https://radiocode.space';

/** «12.08.2026» → Date. Непонятная дата даёт сегодняшний день. */
function датаСтатьи(д: string): Date {
  const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(String(д || ''));
  return m ? new Date(`${m[3]}-${m[2]}-${m[1]}T00:00:00Z`) : new Date();
}

/**
 * ЯЗЫКОВЫЕ ВЕРСИИ ОДНОГО АДРЕСА для карты сайта.
 *
 * 🔴 ЗАЧЕМ. В карте не было НИ ОДНОЙ пометки xhtml:link, то есть поисковик
 * узнавал о переводах только из тегов на самой странице — а до страницы ещё
 * надо дойти. Пометка в карте связывает четыре адреса в одну группу сразу, до
 * первого обхода, и именно так Google просит объявлять языки.
 *
 * Ставим ТОЛЬКО там, где перевод действительно отдаётся с сервера: язык на этом
 * сайте приходит из метки `?lang=` через middleware (заголовок `x-locale`).
 * Страницы станций и каталог музыки написаны по-английски и от метки не
 * меняются — обещать для них четыре версии значило бы соврать карте.
 */
function языковые(путь: string): Record<string, string> {
  // 🔴 БЫЛО `?lang=`, СТАЛО ПРЕФИКС. Google 19.08.2026 прислал по этому сайту
  // «Страница является копией, канонические версии не совпадают»: утром того
  // же дня заработали адреса `/ru/...`, а карта и hreflang продолжали называть
  // форму с меткой. Один материал получил два объявленных адреса.
  //
  // Английский остаётся без префикса — он язык по умолчанию, и корневой путь
  // обязан работать как работал.
  const адрес = `${SITE}${путь}`;
  const сПрефиксом = (я: string) => `${SITE}/${я}${путь}`;
  return {
    en: адрес,
    ru: сПрефиксом('ru'),
    es: сПрефиксом('es'),
    zh: сПрефиксом('zh'),
    'x-default': адрес,
  };
}

export default function sitemap(): MetadataRoute.Sitemap {
  const now = new Date();

  return [
    {
      url: SITE,
      lastModified: now,
      changeFrequency: 'weekly',
      priority: 1,
      // У главной языковые адреса пишутся с косой чертой перед меткой — ровно
      // так они объявлены в hreflang корневой раскладки. Расхождение хотя бы в
      // одном знаке Google считает разными адресами и группу не собирает.
      alternates: {
        languages: {
          en: SITE,
          ru: `${SITE}/?lang=ru`,
          es: `${SITE}/?lang=es`,
          zh: `${SITE}/?lang=zh`,
          'x-default': SITE,
        },
      },
    },
    // Страницы станций: у каждой свой полный список треков и своя разметка.
    // Это единственные страницы сайта с уникальным текстовым содержимым в
    // объёме, поэтому приоритет у них высокий.
    ...stations.map((s) => ({
      url: `${SITE}/station/${s.id}`,
      lastModified: now,
      changeFrequency: 'weekly' as const,
      priority: 0.9,
    })),
    {
      // Каталог всей музыки. До него музыка в карту сайта не попадала вовсе:
      // у треков нет собственных адресов, все 1024 живут внутри страниц
      // станций. Одна плотная страница с разметкой MusicPlaylist делает их
      // машиночитаемыми — в отличие от шестисот «тонких» страниц, которые
      // размыли бы вес самих станций.
      url: `${SITE}/music`,
      lastModified: now,
      changeFrequency: 'weekly',
      priority: 0.9,
    },
    {
      url: `${SITE}/ambassador`,
      lastModified: now,
      changeFrequency: 'weekly',
      priority: 0.8,
      // Пометки добавлены 22.08.2026 по правилу, объявленному в шапке этого
      // файла: ставим их там, где перевод ДЕЙСТВИТЕЛЬНО отдаётся с сервера.
      // Замер того же дня: /ru/ambassador — 1826 знаков кириллицы,
      // /es/ambassador — испанские слова, /zh/ambassador — 672 иероглифа.
      // Без пометки поисковик узнавал о переводах только дойдя до самой
      // страницы, тогда как карта связывает адреса в группу сразу.
      alternates: { languages: языковые('/ambassador') },
    },
    {
      // ТАРИФЫ. Добавлено 30.08.2026 сплошным перебором: страница цен
      // отдаёт HTTP 200 на ВСЕХ ЧЕТЫРЁХ сайтах и НИ НА ОДНОМ не значилась
      // в карте. «Сколько стоит» — один из самых частых запросов, с
      // которым приходят, и человек, ищущий цену, находил кого угодно,
      // кроме нас.
      //
      // Языковые пометки ставятся: тарифы переводятся так же, как
      // остальные текстовые страницы этого сайта.
      url: `${SITE}/tariffs`,
      lastModified: now,
      changeFrequency: 'monthly',
      priority: 0.9,
      alternates: { languages: языковые('/tariffs') },
    },
    {
      // Глоссарий на 28 терминов. Страница /glossary есть на всех четырёх
      // сайтах и на всех трёх остальных стоит в карте сайта
      // (codeofdigitaleternity.com, aifa.digital, aifa.works) — здесь её не
      // было вместе с самой страницей. Текст плотный и уникальный, меняется
      // редко, отсюда monthly.
      url: `${SITE}/glossary`,
      lastModified: now,
      changeFrequency: 'monthly',
      priority: 0.8,
      // То же основание, что и у /ambassador. Замер 22.08.2026:
      // /ru/glossary — 19 693 знака кириллицы, /zh/glossary — 6652 иероглифа,
      // /es/glossary — испанский. Перевод настоящий, значит пометка честная.
      alternates: { languages: языковые('/glossary',
    // Заявление о доступности. Ссылка на него стояла со страницы
    // сканера и отдавала 404: страницы не было ни на одном сайте,
    // кроме aifa.works. Проверено сплошным обходом ссылок 10.09.2026.
    '/accessibility-statement') },
    },
    // Лента новостей и все вышедшие статьи. До появления раздела на этом сайте
    // новостей не было вовсе — /news отвечал 404, — и в карте их, разумеется,
    // тоже не было. Отсечка `тольковышедшие` здесь обязательна: без неё карта
    // сайта выдала бы поисковику подготовленный заранее материал раньше его
    // даты, то есть отменила бы отложенную публикацию с другой стороны.
    {
      url: `${SITE}/news`,
      lastModified: now,
      changeFrequency: 'weekly',
      priority: 0.9,
      alternates: { languages: языковые('/news') },
    },
    ...(тольковышедшие(newsDataВесь as Array<{ date?: string }>) as Array<{ id: string; date: string }>).map((с) => ({
      url: `${SITE}/news/${с.id}`,
      lastModified: датаСтатьи(с.date),
      changeFrequency: 'monthly' as const,
      priority: 0.7,
      alternates: { languages: языковые(`/news/${с.id}`) },
    })),
    // 🔴 РАЗДЕЛА ИССЛЕДОВАНИЯ НЕ БЫЛО В КАРТЕ ВОВСЕ (добавлено 07.09.2026).
    //
    // Замер по четырём сайтам: aifa.works объявляет 96 адресов раздела,
    // здесь — НОЛЬ, при том что все четыре страницы отдают 200 на всех
    // четырёх языках (проверено кодами ответа: 24 адреса, все 200).
    // Для поисковика раздела не существовало.
    //
    // Ту же беду чинили 30.08.2026 на aifa.works и сюда не перенесли —
    // раздел 26 Конституции про то, что чинить надо класс, а не случай,
    // и раздел 9 про одинаковую видимость на четырёх сайтах.
    {
      url: `${SITE}/research`,
      lastModified: now,
      changeFrequency: 'weekly',
      priority: 0.9,
      alternates: { languages: языковые('/research') },
    },
    {
      // Основной материал исследования: живые числа обхода и ссылки на
      // сырые данные. Оттого weekly и высший приоритет среди материалов.
      url: `${SITE}/research/data`,
      lastModified: now,
      changeFrequency: 'weekly',
      priority: 0.85,
      alternates: { languages: языковые('/research/data') },
    },
    {
      // То, чем материал проверяют: метод, ограничения, что не измерялось.
      url: `${SITE}/research/methodology`,
      lastModified: now,
      changeFrequency: 'monthly',
      priority: 0.8,
      alternates: { languages: языковые('/research/methodology') },
    },
    {
      // Открытые данные о мёртвых доменах федерального реестра США.
      url: `${SITE}/research/registry`,
      lastModified: now,
      changeFrequency: 'monthly',
      priority: 0.7,
      alternates: { languages: языковые('/research/registry') },
    },
    // 🔴 ПРАВОВЫХ СТРАНИЦ В КАРТЕ НЕ БЫЛО ВОВСЕ.
    //
    // Обе отвечают 200 (проверено запросом к живому сайту 11.08.2026), обе
    // переведены на четыре языка и обе — документы, по которым человек
    // принимает решение платить. Отсутствие в карте не запрещает их
    // индексировать, но лишает единственного прямого приглашения: на страницы,
    // на которые с главной ведёт только подвал, робот заходит редко и поздно.
    //
    // Приоритет 0.5, changeFrequency yearly: тексты договоров меняются реже
    // всего на сайте, и просить обходить их еженедельно — врать карте.
    {
      url: `${SITE}/service-agreement`,
      lastModified: now,
      changeFrequency: 'yearly',
      priority: 0.5,
      alternates: { languages: языковые('/service-agreement') },
    },
    {
      url: `${SITE}/user-agreement`,
      lastModified: now,
      changeFrequency: 'yearly',
      priority: 0.5,
      alternates: { languages: языковые('/user-agreement') },
    },
    // /contact и /cart в карту НЕ добавлены: этих страниц на radiocode.space
    // нет — обе отвечают 404 (проверено запросом к живому сайту 11.08.2026).
    // Адрес, отдающий 404, в карте сайта — прямая ошибка в Search Console и
    // потеря доверия ко всей карте.
    // 🔴 КАБИНЕТ ИЗ КАРТЫ САЙТА УБРАН.
    //
    // Здесь стояла запись `${SITE}/cabinet` с пояснением «кабинет — публичная
    // точка входа, поэтому он должен быть в карте наравне с остальными».
    // Пояснение противоречило самому кабинету: src/app/cabinet/layout.tsx
    // задаёт `robots: { index: false, follow: false }`. Замерено на живом сайте
    // 08.08.2026 — https://radiocode.space/cabinet отдаёт
    // `<meta name="robots" content="noindex, nofollow">` и при этом лежит в
    // карте сайта.
    //
    // Карта сайта — это список «вот что индексируй». Указывать в ней страницу,
    // которая тут же просит себя не индексировать, — прямое противоречие: в
    // Search Console оно всплывает как ошибка «Отправленный URL помечен
    // noindex», и такие записи снижают доверие ко всей карте. Из четырёх наших
    // сайтов /cabinet в карте был только здесь — на трёх остальных его нет.
  ];
}
