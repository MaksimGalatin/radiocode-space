/**
 * ЧИСЛА ИССЛЕДОВАНИЯ В ЗАПИСИ ЯЗЫКА ЧИТАТЕЛЯ.
 *
 * ПОВОД. В `данные.ts` числа лежат СТРОКАМИ и в русской записи: «95 524»,
 * «0,03». Строка подставляется в текст любого языка как есть, и на
 * английской странице стояло «0,03 %» и «95 524».
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ВНУТРИ СТРАНИЦЫ. Сначала функция жила в
 * `data-client.tsx`, и этого хватило ровно до проверки соседней страницы:
 * `methodology-client.tsx` импортирует тот же блок `Ч` напрямую, минуя
 * локализацию, и английская версия методологии осталась с «53,8» и
 * «11 902». Тот же класс, третье место за один заход.
 *
 * Общий модуль закрывает класс: любая новая страница раздела берёт числа
 * отсюда, а не переизобретает перевод формата.
 *
 * ЧТО КУДА. В русском и испанском десятичный разделитель — запятая, тысячи
 * отбиваются пробелом; в английском и китайском наоборот — точка и запятая.
 * Порядок замен важен: сначала десятичная запятая становится точкой, и лишь
 * потом пробел тысяч становится запятой.
 *
 * Обходит структуру любой глубины: объекты, массивы, вложенные объекты —
 * потому что числа лежат не только в `Ч`, но и в `РОСТ` (массив пар) и в
 * `КОГО_КАСАЕТСЯ` (объект объектов).
 */
export function числаНаЯзыке<T>(о: T, язык: string): T {
  if (язык === 'ru' || язык === 'es') return о;
  const строка = (з: string) =>
    з.replace(/(\d),(\d)/g, '$1.$2').replace(/(\d)[\s ](\d)/g, '$1,$2');
  const обойти = (з: unknown): unknown => {
    if (typeof з === 'string') return строка(з);
    if (Array.isArray(з)) return з.map(обойти);
    if (з && typeof з === 'object') {
      const из: Record<string, unknown> = {};
      for (const к of Object.keys(з as Record<string, unknown>)) {
        из[к] = обойти((з as Record<string, unknown>)[к]);
      }
      return из;
    }
    return з;
  };
  return обойти(о) as T;
}
