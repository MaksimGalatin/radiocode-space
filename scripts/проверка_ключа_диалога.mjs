/**
 * ПРОВЕРКА МЕХАНИЗМА «КЛЮЧ НА ДИАЛОГ» — доказательство, а не обещание.
 *
 * Модуль `lib/dialog-key.ts` обещает право на забвение: удалили соль
 * диалога — запись стала нечитаемой навсегда, даже для нас. Обещание
 * стоит ноль, пока не проверено.
 *
 * Здесь оно проверяется семью способами. Запускать так:
 *
 *     node scripts/проверка_ключа_диалога.mjs
 *
 * Скрипт повторяет вычисления модуля на чистом `node:crypto`, чтобы не
 * зависеть от сборки TypeScript: проверяется САМА КРИПТОГРАФИЯ, а не
 * компилятор. Если модуль однажды разойдётся с этим файлом, разойдутся и
 * ответы — это тоже полезный сигнал.
 *
 * ТРИ ЧИСЛА (раздел 24): запускается руками; ноль платных вызовов;
 * 0 $ — вся работа локальная, сети не касается.
 */

import crypto from 'node:crypto';

const СХЕМА = 'aifa-dialog-key-v1';
const ДЛИНА_СОЛИ = 16;

const соль = () => crypto.randomBytes(ДЛИНА_СОЛИ);

function ключДиалога(ключПользователя, сольДиалога, идДиалога) {
  const инфо = Buffer.from(`${СХЕМА}:${идДиалога}`, 'utf8');
  return Buffer.from(
    crypto.hkdfSync('sha256', ключПользователя, сольДиалога, инфо, 32),
  );
}

function зашифровать(ключ, текст) {
  const iv = crypto.randomBytes(12);
  const ш = crypto.createCipheriv('aes-256-gcm', ключ, iv);
  const шифр = Buffer.concat([ш.update(Buffer.from(текст, 'utf8')), ш.final()]);
  return Buffer.concat([iv, ш.getAuthTag(), шифр]).toString('base64');
}

function расшифровать(ключ, б64) {
  const сырое = Buffer.from(б64, 'base64');
  const д = crypto.createDecipheriv('aes-256-gcm', ключ, сырое.subarray(0, 12));
  д.setAuthTag(сырое.subarray(12, 28));
  return Buffer.concat([д.update(сырое.subarray(28)), д.final()]).toString('utf8');
}

// ── проверки ────────────────────────────────────────────────────────
const проверки = [];
const проверить = (имя, что) => {
  let ок = false;
  let пояснение = '';
  try {
    ок = что() === true;
  } catch (сбой) {
    пояснение = String(сбой).slice(0, 60);
  }
  проверки.push({ имя, ок, пояснение });
};

const ключЧеловека = crypto.randomBytes(32);
const ОБРАЗЕЦ =
  'Привет. Это проверочный диалог: если ты видишь этот текст — расшифровка работает.';

проверить('1. С правильной солью текст читается', () => {
  const с = соль();
  const к = ключДиалога(ключЧеловека, с, 'диалог-1');
  return расшифровать(к, зашифровать(к, ОБРАЗЕЦ)) === ОБРАЗЕЦ;
});

проверить('2. ЗАБВЕНИЕ: без соли расшифровать нельзя', () => {
  const с = соль();
  const к = ключДиалога(ключЧеловека, с, 'диалог-1');
  const шифр = зашифровать(к, ОБРАЗЕЦ);
  // соль «стёрта» — пробуем вывести ключ с любой другой
  try {
    расшифровать(ключДиалога(ключЧеловека, соль(), 'диалог-1'), шифр);
    return false; // прочиталось — забвение НЕ работает
  } catch {
    return true;
  }
});

проверить('3. Соседний диалог не открывается тем же ключом', () => {
  const с1 = соль();
  const с2 = соль();
  const к1 = ключДиалога(ключЧеловека, с1, 'диалог-1');
  const к2 = ключДиалога(ключЧеловека, с2, 'диалог-2');
  const шифр1 = зашифровать(к1, ОБРАЗЕЦ);
  try {
    расшифровать(к2, шифр1);
    return false;
  } catch {
    return true;
  }
});

проверить('4. Та же соль + другой ид диалога = другой ключ', () => {
  const с = соль();
  const а = ключДиалога(ключЧеловека, с, 'диалог-A');
  const б = ключДиалога(ключЧеловека, с, 'диалог-Б');
  return !а.equals(б);
});

проверить('5. Чужой личный ключ не открывает диалог', () => {
  const с = соль();
  const к = ключДиалога(ключЧеловека, с, 'диалог-1');
  const шифр = зашифровать(к, ОБРАЗЕЦ);
  const чужой = ключДиалога(crypto.randomBytes(32), с, 'диалог-1');
  try {
    расшифровать(чужой, шифр);
    return false;
  } catch {
    return true;
  }
});

проверить('6. Вывод ключа воспроизводим (те же входы = тот же ключ)', () => {
  const с = соль();
  return ключДиалога(ключЧеловека, с, 'диалог-1')
    .equals(ключДиалога(ключЧеловека, с, 'диалог-1'));
});

проверить('7. Подмена одного байта шифротекста ловится', () => {
  const с = соль();
  const к = ключДиалога(ключЧеловека, с, 'диалог-1');
  const сырое = Buffer.from(зашифровать(к, ОБРАЗЕЦ), 'base64');
  сырое[сырое.length - 1] ^= 0x01; // портим последний байт
  try {
    расшифровать(к, сырое.toString('base64'));
    return false; // прошло — целостность НЕ проверяется
  } catch {
    return true;
  }
});

проверить('8. Русский текст и эмодзи переживают цикл', () => {
  const с = соль();
  const к = ключДиалога(ключЧеловека, с, 'диалог-1');
  const т = 'Ёлка, приют, 🔥💙🫂 — CODE Eternal. Тест: ЙЦУКЕН ёёё';
  return расшифровать(к, зашифровать(к, т)) === т;
});

// ── итог ────────────────────────────────────────────────────────────
console.log('ПРОВЕРКА МЕХАНИЗМА «КЛЮЧ НА ДИАЛОГ»');
console.log('   схема: ' + СХЕМА);
console.log('');
let прошло = 0;
for (const п of проверки) {
  console.log(
    `   ${п.ок ? 'OK  ' : 'СБОЙ'} ${п.имя}${п.пояснение ? '  — ' + п.пояснение : ''}`,
  );
  if (п.ок) прошло += 1;
}
console.log('');
console.log(`   прошло ${прошло} из ${проверки.length}`);
if (прошло === проверки.length) {
  console.log('   ВЫВОД: забвение работает — удаление соли делает диалог');
  console.log('   нечитаемым навсегда, включая нас самих.');
} else {
  console.log('   ВЫВОД: механизм НЕ доказан. Использовать нельзя.');
}
process.exit(прошло === проверки.length ? 0 : 1);
